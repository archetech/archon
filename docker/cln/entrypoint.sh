#!/usr/bin/env bash
# Runs Core Lightning for the `lightning` profile. Generates the config from
# the environment on every start, reusing the data layout, wallet path and
# variable names of the cl-hive image this replaces, so an existing node keeps
# its identity and channels. Extra arguments are passed to lightningd.
#
# Replaces the base image's /entrypoint.sh, which starts lightningd without
# --lightning-dir and waits on the RPC socket appearing, so a daemon that
# exits before creating it leaves the container running.
set -euo pipefail

die() {
    echo "[cln] ERROR: $*" >&2
    exit 1
}

# The RPC password may come from a file or a Docker secret, as cl-hive allowed.
load_secret() {
    local name=$1 file_var="$1_FILE"
    if [[ -n "${!file_var:-}" ]]; then
        [[ -r "${!file_var}" ]] || die "$file_var is set to '${!file_var}', which is not a readable file"
        printf -v "$name" '%s' "$(cat "${!file_var}")"
    elif [[ -f "/run/secrets/${name,,}" ]]; then
        printf -v "$name" '%s' "$(cat "/run/secrets/${name,,}")"
    fi
}

NETWORK=${NETWORK:-bitcoin}
NETWORK_MODE=${NETWORK_MODE:-tor}
LIGHTNING_PORT=${LIGHTNING_PORT:-9736}
ALIAS=${ALIAS:-cl-hive-node}
RGB=${RGB:-e33502}
LOG_LEVEL=${LOG_LEVEL:-info}
BITCOIN_RPCHOST=${BITCOIN_RPCHOST:-127.0.0.1}
BITCOIN_RPCPORT=${BITCOIN_RPCPORT:-8332}
BITCOIN_RPCUSER=${BITCOIN_RPCUSER:-}
BITCOIN_RPCPASSWORD=${BITCOIN_RPCPASSWORD:-}
ANNOUNCE_ADDR=${ANNOUNCE_ADDR:-}
P2P_BIND=${P2P_BIND:-}
LIGHTNING_ROOT=${LIGHTNING_ROOT:-/data/lightning}
TOR_HOST=${TOR_HOST:-tor}
TOR_HS_DIR=${TOR_HS_DIR:-/tor/cln-service}
TOR_WAIT_SECONDS=${TOR_WAIT_SECONDS:-300}
RPC_SHARE=${RPC_SHARE:-false}
RPC_SHARE_GID=${RPC_SHARE_GID:-}

load_secret BITCOIN_RPCPASSWORD

case "$NETWORK" in
    bitcoin|testnet|signet|regtest) ;;
    *) die "NETWORK must be bitcoin, testnet, signet or regtest, not '$NETWORK'" ;;
esac
case "$NETWORK_MODE" in
    tor|hybrid|clearnet) ;;
    *) die "NETWORK_MODE must be tor, hybrid or clearnet, not '$NETWORK_MODE'" ;;
esac
case "$RPC_SHARE" in
    true)
        [[ "$RPC_SHARE_GID" =~ ^[0-9]+$ ]] || die "RPC_SHARE is true but RPC_SHARE_GID is not a numeric group id: '$RPC_SHARE_GID'"
        ;;
    false) ;;
    *) die "RPC_SHARE must be true or false, not '$RPC_SHARE'" ;;
esac
[[ -n "$BITCOIN_RPCUSER" ]] || die "BITCOIN_RPCUSER is required"
[[ -n "$BITCOIN_RPCPASSWORD" ]] || die "BITCOIN_RPCPASSWORD is required"

# The lightning dir holds the config and the wallet; lightningd keeps the
# rest (hsm_secret, the RPC socket, TLS certificates) in its network
# subdirectory. cl-hive put the wallet in the lightning dir rather than CLN's
# default, so it is named explicitly.
dir=$LIGHTNING_ROOT/$NETWORK
wallet=$dir/lightningd.sqlite3
config=$dir/config

# Without this, lightningd would create an empty wallet next to an existing
# hsm_secret: a node with the right identity and none of its channels.
if [[ -e "$dir/$NETWORK/hsm_secret" && ! -e "$wallet" ]]; then
    die "$dir/$NETWORK/hsm_secret exists but $wallet does not; refusing to start with an empty wallet"
fi

# A Tor-only node must not also be reachable on the host's address. In this
# mode lightningd listens on the container network for Tor, so the host port
# publication has to stay on loopback.
if [[ "$NETWORK_MODE" == tor && -n "$P2P_BIND" && "$P2P_BIND" != 127.0.0.1 ]]; then
    die "NETWORK_MODE is tor but the P2P port is published on '$P2P_BIND'; unset ARCHON_CLN_P2P_BIND or set it to 127.0.0.1"
fi

# The config holds the RPC password.
umask 077
mkdir -p "$dir"

header='# generated by archon cln-entrypoint'
if [[ -f "$config" && "$(head -n 1 "$config")" != "$header" && ! -e "$config.cl-hive.bak" ]]; then
    cp "$config" "$config.cl-hive.bak"
    echo "[cln] Kept the previous config as $config.cl-hive.bak"
fi

# Waits until the command succeeds, for at most TOR_WAIT_SECONDS.
wait_for() {
    local deadline=$((SECONDS + TOR_WAIT_SECONDS))
    until "$@"; do
        ((SECONDS < deadline)) || return 1
        sleep 1
    done
}

announce=()
proxy_lines=()
# socat relays started below, supervised with lightningd.
relays=()
trap 'kill "${relays[@]}" 2>/dev/null || true' EXIT
if [[ "$NETWORK_MODE" != clearnet ]]; then
    echo "[cln] Waiting for $TOR_HOST..."
    wait_for getent hosts "$TOR_HOST" >/dev/null ||
        die "$TOR_HOST did not resolve within ${TOR_WAIT_SECONDS}s; NETWORK_MODE=$NETWORK_MODE needs the tor profile in COMPOSE_PROFILES"

    # With always-use-proxy, lightningd refuses a proxy given by hostname, and
    # an address resolved now would go stale if tor is recreated. socat
    # resolves the host on each connection.
    socat TCP-LISTEN:9050,bind=127.0.0.1,fork,reuseaddr "TCP:$TOR_HOST:9050" &
    relays+=("$!")
    proxy_lines+=("proxy=127.0.0.1:9050")
    [[ "$NETWORK_MODE" == tor ]] && proxy_lines+=("always-use-proxy=true")

    # Tor writes the hostname from the key in this directory, so it always
    # names the onion Tor serves for that key.
    echo "[cln] Waiting for the onion hostname in $TOR_HS_DIR..."
    wait_for test -s "$TOR_HS_DIR/hostname" ||
        die "no onion hostname in $TOR_HS_DIR within ${TOR_WAIT_SECONDS}s; check that tor serves the cln service"
    announce+=("announce-addr=$(tr -d '[:space:]' < "$TOR_HS_DIR/hostname"):$LIGHTNING_PORT")
fi
# An empty announce-addr is a wildcard, which lightningd rejects.
[[ -n "$ANNOUNCE_ADDR" ]] && announce+=("announce-addr=$ANNOUNCE_ADDR")

# Opt-in access to the RPC socket for another container, the Cashu mint's
# `cln` backend. The socket gives full control of the node, and lightningd
# keeps it root-only in a root-only directory, alongside hsm_secret. Rather
# than loosen those, a relay serves a second socket for RPC_SHARE_GID alone,
# in a directory of its own that the other container mounts.
if [[ "$RPC_SHARE" == true ]]; then
    share=$LIGHTNING_ROOT/rpc-share
    mkdir -p "$share"
    chgrp "$RPC_SHARE_GID" "$share"
    chmod 0750 "$share"
    socat "UNIX-LISTEN:$share/lightning-rpc,fork,unlink-early,mode=0660,group=$RPC_SHARE_GID" \
        "UNIX-CONNECT:$dir/$NETWORK/lightning-rpc" &
    relays+=("$!")
else
    # A socket left from an earlier start must not stay reachable.
    rm -f "$LIGHTNING_ROOT/rpc-share/lightning-rpc"
fi

{
    echo "$header"
    echo "network=$NETWORK"
    echo "alias=$ALIAS"
    echo "rgb=$RGB"
    echo "bitcoin-rpcconnect=$BITCOIN_RPCHOST"
    echo "bitcoin-rpcport=$BITCOIN_RPCPORT"
    echo "bitcoin-rpcuser=$BITCOIN_RPCUSER"
    echo "bitcoin-rpcpassword=$BITCOIN_RPCPASSWORD"
    echo "wallet=sqlite3://$wallet"
    echo "log-level=$LOG_LEVEL"
    echo "log-file=$dir/lightningd.log"
    echo "log-file=-"
    # cln-grpc listens on 9736 by default, the P2P port.
    echo "grpc-port=9937"
    echo "clnrest-port=3001"
    echo "clnrest-protocol=https"
    echo "clnrest-host=0.0.0.0"
    echo "min-capacity-sat=${MIN_CAPACITY_SAT:-500000}"
    echo "fee-base=${FEE_BASE:-0}"
    echo "fee-per-satoshi=${FEE_PER_SATOSHI:-100}"
    echo "htlc-minimum-msat=${HTLC_MINIMUM_MSAT:-1000}"
    if [[ "${DUAL_FUND_ENABLED:-true}" == true ]]; then
        echo "experimental-dual-fund"
        echo "funder-policy=${FUNDER_POLICY:-match}"
        echo "funder-policy-mod=${FUNDER_POLICY_MOD:-100}"
        echo "funder-lease-requests-only=false"
        [[ -n "${FUNDER_PER_CHANNEL_MAX:-}" ]] && echo "funder-per-channel-max=$FUNDER_PER_CHANNEL_MAX"
    fi
    echo "bind-addr=0.0.0.0:$LIGHTNING_PORT"
    for line in "${proxy_lines[@]}" "${announce[@]}"; do
        echo "$line"
    done
} > "$config.tmp"
mv "$config.tmp" "$config"

lightningd --lightning-dir="$dir" --network="$NETWORK" "$@" &
lightningd_pid=$!
trap 'kill -TERM "$lightningd_pid" 2>/dev/null || true' TERM INT

pids=("$lightningd_pid" "${relays[@]}")

# Exit when lightningd does, with its status. If a relay dies first, stop
# lightningd and exit non-zero so the restart policy brings them all back.
while :; do
    exited=
    status=0
    wait -n -p exited "${pids[@]}" || status=$?
    # A trapped signal interrupts wait without a process having exited, and
    # leaves the variable unset.
    [[ -n "${exited:-}" ]] && break
done

if [[ "$exited" == "$lightningd_pid" ]]; then
    exit "$status"
fi

echo "[cln] A socat relay exited; stopping lightningd" >&2
kill -TERM "$lightningd_pid" 2>/dev/null || true
wait "$lightningd_pid" || true
exit 1
