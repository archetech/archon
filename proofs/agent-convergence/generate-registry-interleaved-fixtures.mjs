import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { migrationProjection } from '../../tests/convergence/migration-model.mjs';
import { generateRegistryFixtures } from './generate-registry-fixtures.mjs';
import { comparePositions } from './generate-chain-anchor-fixtures.mjs';
const list = xs => `[${xs.join(', ')}]`;
const table = (xs, fallback) => `(fun i => ${list(xs)}.getD i (${fallback}))`;

export function generateRegistryInterleavedFixtures(vectors) {
    // Share all ancestry, complete-order, ordinal, and expected-history guards.
    generateRegistryFixtures(vectors);
    const lines = ['-- Generated by generate-registry-interleaved-fixtures.mjs; do not edit.',
        'import RegistryInterleaved', 'import RegistryFixtures', 'set_option warningAsError true',
        'set_option maxRecDepth 10000', 'set_option maxHeartbeats 4000000',
        'namespace Archon.RegistryInterleavedFixtures'];
    const cases = [];
    let transitions = 0, passChecks = 0;
    vectors.forEach((v, n) => {
        const projection = migrationProjection(v);
        const ids = [...v.ids].sort(), ranks = v.ids.map(id => ids.indexOf(id)), count = ids.length;
        const root = ranks[v.operations.findIndex(op => op.type === 'create')];
        const owners = v.events.map(e => ranks[v.operations.findIndex(op => isDeepStrictEqual(e.operation, op))]);
        const names = [...new Set([v.operations.find(op => op.type === 'create').registration.registry,
            ...v.operations.flatMap(op => op.doc?.didDocumentRegistration ? [op.doc.didDocumentRegistration.registry] : []),
            ...v.events.map(e => e.registry)])].sort();
        const anchored = t => !['local', 'hyperswarm', 'pin'].includes(v.events[t].registry)
            && v.events[t].registry === projection.expectedRegistries[v.ids.indexOf(ids[owners[t]])];
        const anchors = v.events.flatMap((_, t) => anchored(t) ? [t] : []).sort((a, b) =>
            names.indexOf(v.events[a].registry) - names.indexOf(v.events[b].registry)
            || comparePositions(v.events[a].ordinal, v.events[b].ordinal));
        const rank = v.events.map((_, t) => anchored(t) ? anchors.indexOf(t) : anchors.length + owners[t]);
        const all = list(ids.map((_, i) => i)), receipts = list(anchors.map((_, i) => i));
        const size = anchors.length + count;
        const g = `RegistryFixtures.graph${n}`, ordered = `RegistryFixtures.ordered${n}`, bounded = `RegistryFixtures.depthBound${n}`;
        const r = `receipts${n}`, a = `anchors${n}`, m = `raw${n}`, c = `compiled${n}`, owner = `owner${n}`, priority = `priority${n}`;
        const seed = v.expectedEvents[0];
        assert.equal(owners[seed], root);
        assert(anchored(seed));
        assert.equal(rank[seed], Math.min(...anchors.filter(t => owners[t] === root).map(t => rank[t])));
        lines.push(`def ${r} : RegistryReceipts := {`, `  size := ${anchors.length}`,
            `  owner := ${table(anchors.map(t => owners[t]), count)}`,
            `  registry := ${table(anchors.map(t => names.indexOf(v.events[t].registry)), names.length)}`,
            `  chain := ${table(names.map(name => String(!['local', 'hyperswarm', 'pin'].includes(name))), 'false')}`,
            `  accepted := fun i => decide (i < ${anchors.length})`, '}',
            `abbrev ${a} := registryAnchors ${g} ${r}`, `abbrev ${owner} := chainOwner ${a}`,
            `abbrev ${priority} := chainPriority ${a} ${receipts}`,
            `abbrev ${m} := registryEvents ${g} ${a}`,
            `abbrev ${c} := chainGraph (registryModel ${g}) ${a} ${receipts}`,
            `def selected${n} := ${all}.map ${priority}`);
        lines.push(`def positions${n} : Nat → List Nat := ${table(anchors.map(t => list(v.events[t].ordinal)), '[]')}`,
            `theorem ordinalRanks${n} : RegistryOrdinalRanks ${g} ${r} positions${n} := by`,
            '  intro x y xv yv same',
            `  have xb : x < ${anchors.length} := eligible_lt _ _ _ xv`,
            `  have yb : y < ${anchors.length} := eligible_lt _ _ _ yv`,
            `  have finite : ∀ x y : Fin ${anchors.length},`,
            `      eligible ${a} (${r}.owner x.val) x.val = true → eligible ${a} (${r}.owner y.val) y.val = true →`,
            `      ${r}.registry x.val = ${r}.registry y.val →`,
            `      (x.val < y.val ↔ compare (positions${n} x.val) (positions${n} y.val) = .lt) := by decide`,
            '  exact finite ⟨x, xb⟩ ⟨y, yb⟩ xv yv same');
        for (let x = 0; x < count; x++) for (let y = x + 1; y < count; y++) {
            const previous = v.operations[v.ids.indexOf(ids[x])].previd;
            if (!previous || previous !== v.operations[v.ids.indexOf(ids[y])].previd) continue;
            lines.push(`example : ${priority} ${x} < ${priority} ${y} ↔`,
                `    compare (positions${n} (winner ${a} ${x} ${receipts})) (positions${n} (winner ${a} ${y} ${receipts})) = .lt :=`,
                `  registry_sibling_priority ${g} ${r} positions${n} ordinalRanks${n} (by decide) ${receipts} ${x} ${y} ${ids.indexOf(previous)} (by decide) (by decide) (by decide) (by decide)`);
        }
        // The original audit orders cover gossip-first provisional duplicates.
        // Add a distinct wrong-chain-first delivery without changing signed data.
        const wrong = v.events.findIndex((e, t) => !anchored(t) && e.registry !== 'hyperswarm'
            && e.operation.previd === ids[root]);
        assert(wrong >= 0, 'wrong-chain child of genesis required');
        const gossip = v.events.findIndex((e, t) => e.registry === 'hyperswarm' && owners[t] === owners[wrong]);
        assert(gossip >= 0, 'matching gossip receipt required');
        const rest = v.events.map((_, t) => t).filter(t => t !== wrong && t !== gossip).sort((a, b) =>
            owners[a] - owners[b] || names.indexOf(v.events[a].registry) - names.indexOf(v.events[b].registry)
            || comparePositions(v.events[a].ordinal, v.events[b].ordinal));
        const orders = [...v.orders, [wrong, gossip, ...rest]];
        assert.equal(new Set(orders.map(order => JSON.stringify(order))).size, orders.length, 'distinct interleaved orders required');
        for (const [k, order] of orders.entries()) {
            const delivery = list(order.map(t => rank[t])), pr = `projection${n}_${k}`;
            lines.push(`theorem ${pr} : PriorityProjection ${m} ${c} ${owner} ${priority} ${delivery} selected${n} ${g}.size := by`,
                '  constructor', '  · rfl');
            const fields = [
                [`i.val ∈ ${delivery} → eligible ${m} p.val i.val = true`, `${priority} (${owner} i.val) ∈ selected${n} ∧ eligible ${c} (${priority} p.val) (${priority} (${owner} i.val)) = true ∧ ${priority} (${owner} i.val) ≤ i.val`],
                [`i.val ∈ selected${n} → eligible ${c} (${priority} p.val) i.val = true`, `i.val ∈ ${delivery} ∧ eligible ${m} p.val i.val = true`],
                [`i.val ∈ selected${n} → eligible ${c} (${priority} p.val) i.val = true`, `i.val = ${priority} (${owner} i.val) ∧ ${owner} i.val < ${count}`],
            ];
            for (const [premise, conclusion] of fields) lines.push('  · intro p scope i member valid',
                `    have bound : i < ${size} := eligible_lt _ _ _ valid`,
                `    have checked : ∀ p : Fin ${count}, ∀ i : Fin ${size}, ${premise} → ${conclusion} := by decide`,
                '    exact checked ⟨p, scope⟩ ⟨i, bound⟩ member valid');
            const expected = list(v.expected.map(i => ranks[i]));
            lines.push(`example : (interleavedUntilStable ${m} ${owner} ${root} ${delivery} (${m}.level ${root} + 1) []).map (fun path => ${root} :: path.map ${owner}) = some ${expected} := by`,
                `  have h := interleaved_registry_cold ${g} ${r} ${ordered} ${bounded} (by decide) (by decide) ${receipts} ${all} ${delivery} [] ${pr} (.nil _) (by decide)`,
                '  exact h.trans (by decide)');
            // Track full receipt identities separately. Equal provisional ranks
            // do not authorize replacing the first observed receipt's metadata.
            const insert = (path, t) => {
                const duplicate = path.findIndex(current => owners[current] === owners[t]);
                if (duplicate >= 0) {
                    const current = path[duplicate];
                    if (anchored(t) && (!anchored(current) || rank[t] < rank[current])) {
                        const after = [...path]; after[duplicate] = t; return after;
                    }
                    return path;
                }
                const previous = ids.indexOf(v.events[t].operation.previd);
                const index = path.findIndex(current => owners[current] === previous);
                if (index < 0) return path;
                if (index === path.length - 1) return [...path, t];
                return rank[t] < rank[path[index + 1]] ? [...path.slice(0, index + 1), t] : path;
            };
            const suffix = path => list(path.slice(1).map(t => rank[t]));
            let path = [seed], stopped = false;
            const passBound = count + 1, passes = [];
            for (let pass = 0; pass < passBound; pass++) {
                const before = path, steps = [];
                for (const t of order) {
                    const after = insert(path, t);
                    lines.push(`example : interleavedInsert ${m} ${owner} ${root} ${rank[t]} ${suffix(path)} = ${suffix(after)} := by decide`);
                    transitions++; path = after; steps.push(path);
                }
                lines.push(`example : interleavedPass ${m} ${owner} ${root} ${delivery} ${suffix(before)} = ${suffix(path)} := by decide`);
                passChecks++; passes.push(steps);
                const same = isDeepStrictEqual(before, path);
                assert.equal(suffix(before) === suffix(path), same, 'projected stopping differs from full receipt stopping');
                if (same) { stopped = true; break; }
            }
            assert(stopped, 'exceeded ancestry stopping bound');
            assert.deepEqual(path, v.expectedEvents, 'interleaved trace disagrees with expected receipts');
            cases.push({ vector: n, seed, order, passBound, passes });
        }
    });
    lines.push('end Archon.RegistryInterleavedFixtures', '');
    return { lean: lines.join('\n'), cases, transitions, passChecks };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const vectors = JSON.parse(readFileSync(new URL('../../tests/convergence/migration-vectors.json', import.meta.url), 'utf8'));
    const { lean, cases } = generateRegistryInterleavedFixtures(vectors);
    for (const [path, result] of [['./RegistryInterleavedFixtures.lean', lean], ['../../tests/convergence/registry-interleaved-cases.json', '[\n' + cases.map(c => JSON.stringify(c)).join(',\n') + '\n]\n']]) {
        const target = new URL(path, import.meta.url);
        if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8'), result, 'registry interleaved fixtures are stale');
        else writeFileSync(target, result);
    }
}
