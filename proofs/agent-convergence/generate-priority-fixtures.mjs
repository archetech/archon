import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { deriveChainSuccessorModel } from './generate-chain-successor-fixtures.mjs';

export function generatePriorityFixtures(vectors) {
    const lines = ['-- Generated by generate-priority-fixtures.mjs; do not edit.',
        'import PriorityProjection', 'import InterleavedFixtures', 'import ChainSuccessorFixtures',
        'set_option warningAsError true', 'namespace Archon.PriorityFixtures'];
    const list = xs => `[${xs.join(', ')}]`;
    let count = 0;
    vectors.forEach((v, n) => {
        const { ops, root, owners, anchorRanks, anchors, expected } = deriveChainSuccessorModel(v);
        const ranks = v.events.map((_, t) => anchorRanks.get(t) ?? anchors.length + owners[t]);
        assert.equal(new Set(ranks).size, ranks.length, 'one provisional representation per operation required');
        const rawEvidence = ranks.slice().sort((a, b) => a - b);
        const size = anchors.length + ops.length;
        const raw = `InterleavedFixtures.model${n}`, owner = `InterleavedFixtures.owner${n}`;
        const compiled = `ChainSuccessorFixtures.graph${n}`, priority = `priority${n}`;
        const events = `events${n}`, selected = `selected${n}`;
        const choose = op => Math.min(...ranks.filter((_, token) => owners[token] === op));
        const final = expected.map(choose);
        assert(final.every(Number.isSafeInteger), 'expected operation needs retained evidence');
        lines.push(`abbrev ${priority} := chainPriority ChainSuccessorFixtures.anchors${n} ${list(anchors)}`,
            `def ${events} : List Nat := ${list(rawEvidence)}`,
            `def ${selected} : List Nat := ${list(ops.map((_, i) => i))}.map ${priority}`,
            `theorem projection${n} : PriorityProjection ${raw} ${compiled} ${owner} ${priority} ${events} ${selected} ${ops.length} := by`,
            '  constructor', '  · rfl');
        const fields = [
            { premise: `i.val ∈ ${events} → eligible ${raw} p.val i.val = true`,
                conclusion: `${priority} (${owner} i.val) ∈ ${selected} ∧ eligible ${compiled} (${priority} p.val) (${priority} (${owner} i.val)) = true ∧ ${priority} (${owner} i.val) ≤ i.val` },
            { premise: `i.val ∈ ${selected} → eligible ${compiled} (${priority} p.val) i.val = true`,
                conclusion: `i.val ∈ ${events} ∧ eligible ${raw} p.val i.val = true` },
            { premise: `i.val ∈ ${selected} → eligible ${compiled} (${priority} p.val) i.val = true`,
                conclusion: `i.val = ${priority} (${owner} i.val) ∧ ${owner} i.val < ${ops.length}` },
        ];
        for (const field of fields) {
            lines.push('  · intro p scope i member valid',
                `    have bound : i < ${size} := eligible_lt _ _ _ valid`,
                `    have checked : ∀ p : Fin ${ops.length}, ∀ i : Fin ${size}, ${field.premise} → ${field.conclusion} := by decide`,
                '    exact checked ⟨p, scope⟩ ⟨i, bound⟩ member valid');
        }
        lines.push(`theorem agreement${n} : interleavedUntilStable ${raw} ${owner} ${ops.length} ${events} (${raw}.level ${ops.length} + 1) [] = replayCold ${compiled} (${priority} ${root}) ${selected} := by`,
            `  exact interleaved_and_priority_replay_agree ${raw} ${compiled} ${owner} ${priority} ${events} ${selected} ${ops.length} ${ops.length} ${root} [] projection${n} (by decide) InterleavedFixtures.descending${n} (.nil _) (by decide) (by decide) (by decide) (by decide) ChainSuccessorFixtures.acyclic${n} (by decide) (by decide)`);
        for (const order of v.orders) {
            assert(order.every(t => Number.isInteger(t) && v.events[t]), 'unknown event token');
            assert.equal(new Set(order).size, v.events.length, 'complete evidence required');
            const delivery = list(order.map(t => ranks[t]));
            lines.push(`example : interleavedUntilStable ${raw} ${owner} ${ops.length} ${delivery} (${raw}.level ${ops.length} + 1) [] = some ${list(final)} := by`,
                `  rw [interleaved_replay_same_evidence ${raw} ${owner} ${delivery} ${events} ${ops.length} [] [] InterleavedFixtures.descending${n} (.nil _) (.nil _) (bounded_membership_agrees ${size} _ _ (by decide) (by decide) (by decide))]`,
                `  rw [agreement${n}, cold_replay_converges ${compiled} (${priority} ${root}) ${selected} ChainSuccessorFixtures.acyclic${n} (by decide) (by decide)]`,
                '  decide');
            count++;
        }
    });
    lines.push('end Archon.PriorityFixtures', '');
    return { result: lines.join('\n'), count };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const input = JSON.parse(readFileSync(new URL('../../tests/convergence/chain-successor-vectors.json', import.meta.url), 'utf8'));
    const { result } = generatePriorityFixtures(input);
    const destination = new URL('./PriorityFixtures.lean', import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), result, 'priority fixtures are stale');
    else writeFileSync(destination, result);
}
