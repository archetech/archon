import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export function generateRecordFixtures(vectors, fixture) {
    const history = vectors.histories.find(h => h.registry === fixture.registry);
    assert(history, 'unknown history');
    const sorted = history.ids.slice().sort();
    const list = xs => `[${xs.join(', ')}]`;
    const lines = ['-- Generated by generate-record-fixtures.mjs; do not edit.',
        'import Fixtures', '', 'set_option warningAsError true', '',
        'namespace Archon.RecordFixtures', ''];
    const model = `Fixtures.model${vectors.histories.indexOf(history)}`;
    const rootIndex = history.operations.findIndex(op => op.type === 'create');
    const root = sorted.indexOf(history.ids[rootIndex]);
    const depth = index => Math.max(0, ...history.operations.flatMap((op, i) =>
        op.previd === history.ids[index] ? [1 + depth(i)] : []));
    const warmPasses = depth(rootIndex) + 1;
    [...fixture.cases, ...fixture.replayCases].forEach((c, index) => {
        const settled = index < fixture.cases.length;
        assert.deepEqual(c.initial, c.initial.map((_, i) => i), 'initial history must be a prefix');
        const selected = c.initial.map(i => c.events[i].operation);
        assert.equal(new Set(selected).size, selected.length, 'initial path must have unique IDs');
        if (selected.length || settled) assert.equal(history.operations[selected[0]]?.type, 'create', 'initial path must start at genesis');
        for (const [position, op] of selected.entries()) {
            if (position) assert.equal(history.operations[op].previd, history.ids[selected[position - 1]], 'initial path must be predecessor linked');
        }
        const record = token => {
            const e = c.events[token];
            assert(e && history.operations[e.operation], 'unknown operation');
            if (settled) assert(selected.includes(e.operation), 'only duplicates of the settled path are supported');
            assert(['local', 'hyperswarm', 'pin'].includes(e.registry), 'only provisional registry evidence is supported');
            const operation = history.operations[e.operation];
            const payload = JSON.stringify({ operation, opid: history.ids[e.operation], registry: e.registry,
                ordinal: e.ordinal, time: operation.proof.created, did: history.did });
            // Complete event JSON is an opaque String payload, not merely a receipt index.
            return [
                `opaque payload${index}_${token} : String := ${JSON.stringify(payload)}`,
                `def ${ref(token)} : EventRecord String := ⟨${sorted.indexOf(history.ids[e.operation])}, ${e.registry === fixture.registry}, payload${index}_${token}⟩`,
            ];
        };
        const ref = token => {
            assert(c.events[token], 'unknown receipt');
            return `receipt${index}_${token}`;
        };
        lines.push(`-- ${c.name}`,
            ...c.events.flatMap((_, token) => record(token)),
            `def initial${index} : List (EventRecord String) := ${list(c.initial.map(ref))}`,
            `def evidence${index} : List (EventRecord String) := ${list(c.events.map((_, i) => ref(i)))}`,
            `def expected${index} : List (EventRecord String) := ${list(c.expected.map(ref))}`,
        );
        if (settled) lines.push(
            `example : recordPass evidence${index} initial${index} = expected${index} := by rfl`,
            `example : recordsUntilStable evidence${index} 2 initial${index} = some expected${index} := by rw [record_loop_terminates]; rfl`,
            `example : recordPass evidence${index}.reverse expected${index} = expected${index} := by rfl`);
        const genesis = c.events.findIndex(e => history.operations[e.operation].type === 'create');
        assert(genesis >= 0, 'cold replay requires genesis evidence');
        assert(c.expected.length > 0, 'cold replay requires a nonempty expected history');
        const state = indices => `(${ref(indices[0])}, ${list(indices.slice(1).map(ref))})`;
        assert(c.replayPasses.length > 0, 'expected replay passes are required');
        assert.deepEqual(c.replayPasses.at(-1), c.expected, 'replay passes must reach the expected history');
        const start = state(c.replayPasses[0]);
        const target = state(c.expected);
        const transitions = c.replayPasses.slice(1).map((next, i) =>
            `  have pass${i} : historyPass ${model} ${root} evidence${index} ${state(c.replayPasses[i])} = ${state(next)} := by rfl`);
        const steps = transitions.map((_, i) => `pass${i}`);
        lines.push(`example : replayFullCold ${model} ${root} evidence${index} = some ${target} := by`,
            `  have initialized : coldEventPass ${model} ${root} evidence${index} none = some ${start} := by rfl`,
            ...transitions,
            `  have fixed : historyPass ${model} ${root} evidence${index} ${target} = ${target} := by rfl`,
            '  unfold replayFullCold', '  rw [initialized]', '  simp only [Option.bind_some]',
            `  apply stop_of_reaches _ ${start} ${target} (${model}.level ${root} + 1)`,
            `  · change iterateState _ ${warmPasses} _ = _`,
            `    simp only [iterateState, ${[...steps, 'fixed'].join(', ')}]`,
            '  · exact fixed', '');
    });
    lines.push('end Archon.RecordFixtures', '');
    return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const read = path => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
    const result = generateRecordFixtures(read('../../tests/convergence/vectors.json'), read('../../tests/convergence/record-cases.json'));
    const destination = new URL('./RecordFixtures.lean', import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), result, 'record fixtures are stale');
    else writeFileSync(destination, result);
}
