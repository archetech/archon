import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { comparePositions } from './generate-chain-anchor-fixtures.mjs';

// Fixed same-key agent/data-update domain. Signatures and live replay are checked
// by the runtime suites; this bridge derives the graph and complete ordinal ranks.
export function generateChainSuccessorFixtures(vectors) {
    const lines = ['-- Generated by generate-chain-successor-fixtures.mjs; do not edit.',
        'import ChainSuccessors', 'set_option warningAsError true', 'namespace Archon.ChainSuccessorFixtures'];
    const list = xs => `[${xs.join(', ')}]`;
    const membership = size => `(bounded_membership_agrees ${size} _ _ (by decide) (by decide) (by decide))`;
    let count = 0;
    vectors.forEach((v, n) => {
        assert.equal(v.operations.length, v.ids.length);
        assert.equal(new Set(v.ids).size, v.ids.length);
        const sorted = [...v.ids].sort();
        const ops = sorted.map(id => v.operations[v.ids.indexOf(id)]);
        const roots = ops.flatMap((op, i) => op.type === 'create' ? [i] : []);
        assert.equal(roots.length, 1, 'one genesis required');
        const root = roots[0];
        const create = ops[root];
        assert.equal(v.did, 'did:cid:' + sorted[root]);
        assert.deepEqual(create.registration, { version: 1, type: 'agent', registry: 'BTC:signet' });
        assert.equal(create.controller, undefined);
        assert.equal(create.previd, undefined);
        const parents = ops.map((op, i) => {
            if (i === root) return null;
            assert.equal(op.type, 'update');
            assert.equal(op.did, v.did);
            assert.deepEqual(Object.keys(op.doc), ['didDocumentData'], 'only data updates supported');
            assert.equal(op.proof.verificationMethod, v.did + '#key-1', 'fixed key required');
            const parent = sorted.indexOf(op.previd);
            assert(parent >= 0, 'predecessor must be in the operation table');
            return parent;
        });
        const height = (i, seen = new Set()) => {
            assert(!seen.has(i), 'cyclic predecessor graph');
            return parents[i] === null ? 0 : 1 + height(parents[i], new Set([...seen, i]));
        };
        const depths = ops.map((_, i) => height(i));
        const levels = depths.map(d => Math.max(...depths) - d);
        const owners = v.events.map(e => {
            const matches = ops.flatMap((op, i) => isDeepStrictEqual(op, e.operation) ? [i] : []);
            assert.equal(matches.length, 1, 'event must match one operation');
            assert(['hyperswarm', 'BTC:signet'].includes(e.registry), 'foreign registries are outside this model');
            return matches[0];
        });
        const anchorTokens = v.events.flatMap((e, i) => e.registry === 'BTC:signet' ? [i] : []);
        for (const i of anchorTokens) assert(Array.isArray(v.events[i].ordinal) && v.events[i].ordinal.length && v.events[i].ordinal.every(x => Number.isSafeInteger(x) && x >= 0), 'complete ordinal required');
        anchorTokens.sort((a, b) => comparePositions(v.events[a].ordinal, v.events[b].ordinal));
        for (let i = 1; i < anchorTokens.length; i++) assert(comparePositions(v.events[anchorTokens[i - 1]].ordinal, v.events[anchorTokens[i]].ordinal) < 0, 'tied ordinals excluded');
        const anchorRanks = new Map(anchorTokens.map((token, i) => [token, i]));
        const anchors = anchorTokens.map((_, i) => i);
        const all = ops.map((_, i) => i);
        const expected = v.expected.map(i => sorted.indexOf(v.ids[i]));
        assert(expected.every(i => i >= 0), 'unknown expected operation');
        const table = (values, fallback) => `(fun i => ${list(values)}.getD i (${fallback}))`;
        const g = `graph${n}`, a = `anchors${n}`, o = `ops${n}`, total = ops.length + anchors.length;
        lines.push(`def ${o} : Model := ⟨${ops.length}, ${table(parents.map(p => p === null ? 'none' : 'some ' + p), 'none')}, fun _ => true, ${table(levels, '0')}⟩`,
            `def ${a} : AnchorModel := ⟨${anchors.length}, ${table(anchorTokens.map(t => 'some ' + owners[t]), 'none')}, fun _ => true, fun _ => 0⟩`,
            `abbrev ${g} := chainGraph ${o} ${a} ${list(anchors)}`,
            `theorem acyclic${n} : WellFoundedEdges ${g} := by`, '  intro p i h',
            `  have bound : i < ${total} := eligible_lt _ _ _ h`,
            `  have cases : ${Array.from({ length: total }, (_, i) => 'i = ' + i).join(' ∨ ')} := by omega`,
            `  rcases cases with ${Array(total).fill('rfl').join(' | ')} <;> simp [eligible, ${g}, chainGraph, ${o}, ${a}, chainOwner, chainPriority, anchorScan, anchorStep, List.foldl] at h`,
            '  all_goals subst p; decide',
            `theorem settled${n} : chainReplay ${o} ${a} ${list(anchors)} ${root} ${list(all)} = some ${list(expected)} := by`,
            `  rw [chain_replay_converges ${o} ${a} ${list(anchors)} ${root} ${list(all)} acyclic${n} (by decide) (by decide)]`, '  decide');
        for (const order of v.orders) {
            assert(order.every(i => Number.isInteger(i) && v.events[i]), 'unknown event token');
            assert.equal(new Set(order).size, v.events.length, 'complete evidence required');
            const delivery = order.map(i => owners[i]);
            const anchorDelivery = order.filter(i => anchorRanks.has(i)).map(i => anchorRanks.get(i));
            lines.push(`example : chainReplay ${o} ${a} ${list(anchorDelivery)} ${root} ${list(delivery)} = some ${list(expected)} := by`,
                `  rw [← chain_successors_same_evidence ${o} ${a} ${list(anchors)} ${list(anchorDelivery)} ${list(all)} ${list(delivery)} ${root} ${membership(anchors.length)} ${membership(ops.length)} acyclic${n} (by decide) (by decide)]`, `  exact settled${n}`);
            count++;
        }
    });
    lines.push('end Archon.ChainSuccessorFixtures', '');
    return { result: lines.join('\n'), count };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const input = JSON.parse(readFileSync(new URL('../../tests/convergence/chain-successor-vectors.json', import.meta.url), 'utf8'));
    const { result } = generateChainSuccessorFixtures(input);
    const destination = new URL('./ChainSuccessorFixtures.lean', import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), result, 'chain successor fixtures are stale');
    else writeFileSync(destination, result);
}
