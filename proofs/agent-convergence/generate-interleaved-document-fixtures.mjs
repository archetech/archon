import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { documentGraph } from '../../tests/convergence/document-model.mjs';
const list = xs => `[${xs.join(', ')}]`;
const state = x => x === 'deleted' ? 'AgentState.deleted' : `(AgentState.active ${x})`;

export function generateInterleavedDocumentFixtures(vectors) {
    const lines = ['-- Generated by generate-interleaved-document-fixtures.mjs; do not edit.',
        'import InterleavedAuthorization', 'import DocumentFixtures', 'import ChainSuccessors',
        'set_option warningAsError true', 'set_option maxRecDepth 10000',
        'set_option maxHeartbeats 4000000', 'namespace Archon.InterleavedDocumentFixtures'];
    let count = 0;
    for (const [v, vector] of vectors.entries()) {
        const { ranks, root } = documentGraph(vector);
        const n = ranks.length, g = `DocumentFixtures.graph${v}`, m = `events${v}`;
        const splits = ranks.map((_, i) => `i = ${i}`).join(' ∨ ');
        const cases = ranks.map(() => 'rfl').join(' | ');
        lines.push(`abbrev ${m} := documentEvents ${g} ${n} id (fun _ => true)`,
            `theorem ordered${v} : AncestryOrdered (documentAgent ${g}) := by`,
            '  intro i p parent', `  by_cases bound : i < ${n}`,
            `  · have cases : ${splits} := by omega`,
            `    rcases cases with ${cases} <;> simp [documentAgent, ${g}] at parent`,
            '    all_goals subst p; decide',
            `  · have outside : ${n} ≤ i := by omega`,
            `    simp only [documentAgent, ${g}] at parent`,
            '    rw [List.getD_eq_getElem?_getD, List.getElem?_eq_none (by simpa using outside)] at parent',
            '    simp at parent',
            `theorem bounded${v} : DepthBounded (documentAgent ${g}) := by`,
            '  intro i bound', `  have small : i < ${n} := bound`,
            `  have checked : ∀ i : Fin ${n}, (documentAgent ${g}).depth i.val < (documentAgent ${g}).size := by decide`,
            '  exact checked ⟨i, small⟩');
        for (const [s, scenario] of vector.scenarios.entries()) {
            assert.equal(ranks[scenario.expected[0]], root, 'expected path must start at genesis');
            const evidence = [...new Set(scenario.orders[0].map(i => ranks[i]))].sort((a, b) => a - b);
            const tail = scenario.expected.slice(1).map(i => ranks[i]);
            const canonical = `canonical${v}_${s}`;
            lines.push(`def evidence${v}_${s} : List Nat := ${list(evidence)}`,
                `theorem ${canonical} : (interleavedUntilStable ${m} id ${root} evidence${v}_${s} (${m}.level ${root} + 1) []).map (fun path => (${root} :: path, runAgent (documentAgent ${g}) (.active ${g}.initialDocument) (path.map id))) = some (${list(scenario.expected.map(i => ranks[i]))}, some ${state(scenario.finalState)}) := by`,
                `  obtain ⟨result, final, replay, canonical, ran, _⟩ := interleaved_document_converges ${g} ${n} id (fun _ => true) ordered${v} bounded${v} (by decide) evidence${v}_${s} ${root} [] (.active ${g}.initialDocument) (.nil _) (agent_state_root _ (by decide))`,
                `  have selected : result = ${list(tail)} := canonical.trans (by decide)`,
                '  rw [replay, Option.map_some, selected]',
                '  decide');
            for (const order of scenario.orders) {
                const delivery = order.map(i => ranks[i]);
                assert(delivery.every(Number.isInteger), 'unknown operation');
                assert.deepEqual([...new Set(delivery)].sort((a, b) => a - b), evidence, 'scenario evidence differs');
                lines.push(`example : (interleavedUntilStable ${m} id ${root} ${list(delivery)} (${m}.level ${root} + 1) []).map (fun path => (${root} :: path, runAgent (documentAgent ${g}) (.active ${g}.initialDocument) (path.map id))) = some (${list(scenario.expected.map(i => ranks[i]))}, some ${state(scenario.finalState)}) := by`,
                    `  rw [interleaved_replay_same_evidence ${m} id ${list(delivery)} evidence${v}_${s} ${root} [] [] (document_events_descending ${g} ${n} id (fun _ => true) ordered${v} bounded${v}) (.nil _) (.nil _) (bounded_membership_agrees ${n} _ _ (by decide) (by decide) (by decide))]`,
                    `  exact ${canonical}`);
                count++;
            }
        }
    }
    lines.push('end Archon.InterleavedDocumentFixtures', '');
    return { result: lines.join('\n'), count };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const input = JSON.parse(readFileSync(new URL('../../tests/convergence/document-vectors.json', import.meta.url), 'utf8'));
    const { result } = generateInterleavedDocumentFixtures(input);
    const destination = new URL('./InterleavedDocumentFixtures.lean', import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), result, 'interleaved document fixtures are stale');
    else writeFileSync(destination, result);
}
