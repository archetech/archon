import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { deriveChainSuccessorModel } from './generate-chain-successor-fixtures.mjs';

export function generateInterleavedFixtures(vectors) {
    const lines = ['-- Generated by generate-interleaved-fixtures.mjs; do not edit.',
        'import InterleavedBound', 'set_option warningAsError true', 'namespace Archon.InterleavedFixtures'];
    const cases = [];
    const list = values => `[${values.join(', ')}]`;
    vectors.forEach((v, n) => {
        const model = deriveChainSuccessorModel(v);
        const { ops, parents, levels, owners, anchorTokens, anchorRanks, expected } = model;
        const owner = [...anchorTokens.map(t => owners[t]), ...ops.map((_, i) => i)];
        const predecessor = owner.map(op => parents[op] ?? ops.length);
        const rank = v.events.map((_, t) => anchorRanks.get(t) ?? anchorTokens.length + owners[t]);
        assert.equal(new Set(rank).size, rank.length, 'one provisional representation per operation required');
        const token = new Map(rank.map((r, t) => [r, t]));
        const table = values => `(fun i => ${list(values)}.getD i 0)`;
        const someParents = predecessor.map(p => 'some ' + p);
        const virtualLevel = Math.max(...levels) + 1;
        const passBound = virtualLevel + 1;
        const operationLevels = [...levels, virtualLevel];
        const validPath = path => path.reduceRight(tail => `(.cons (by decide) (by decide) ${tail})`, '(.nil _)');
        lines.push(`def model${n} : Model := ⟨${owner.length}, (fun i => ${list(someParents)}.getD i none), fun _ => true, ${table(operationLevels)}⟩`,
            `def owner${n} : Nat → Nat := ${table(owner)}`,
            `theorem descending${n} : InterleavedDescending model${n} owner${n} := by`,
            '  intro p i h',
            `  have bound : i < ${owner.length} := eligible_lt _ _ _ h`,
            `  have cases : ${owner.map((_, i) => 'i = ' + i).join(' ∨ ')} := by omega`,
            `  rcases cases with ${owner.map(() => 'rfl').join(' | ')} <;> simp [eligible, model${n}] at h`,
            '  all_goals subst p; decide');
        const insert = (parent, incoming, path) => {
            if (!path.length) return predecessor[incoming] === parent ? [incoming] : [];
            const [current, ...rest] = path;
            if (predecessor[incoming] === parent) {
                if (owner[current] === owner[incoming]) return [Math.min(current, incoming), ...rest];
                return incoming < current ? [incoming] : path;
            }
            return [current, ...insert(owner[current], incoming, rest)];
        };
        for (const order of v.orders) {
            assert(order.every(t => Number.isInteger(t) && v.events[t]), 'unknown event token');
            assert.equal(new Set(order).size, v.events.length, 'complete evidence required');
            let path = [];
            const passes = [];
            let stopped = false;
            for (let pass = 0; pass < passBound; pass++) {
                const before = path;
                const steps = [];
                for (const t of order) {
                    const after = insert(ops.length, rank[t], path);
                    lines.push(`example : interleavedInsert model${n} owner${n} ${ops.length} ${rank[t]} ${list(path)} = ${list(after)} := by decide`);
                    path = after;
                    steps.push(path.map(r => token.get(r)));
                }
                lines.push(`example : interleavedPass model${n} owner${n} ${ops.length} ${list(order.map(t => rank[t]))} ${list(before)} = ${list(path)} := by decide`);
                if (before.length) {
                    lines.push(`example : (interleavedPass model${n} owner${n} ${ops.length} ${list(order.map(t => rank[t]))} ${list(before)}).headD model${n}.size = winner model${n} ${ops.length} ${list(order.map(t => rank[t]))} := interleaved_next_settles _ _ _ _ _ _ (by decide) (by decide)`);
                }
                passes.push(steps);
                if (JSON.stringify(before) === JSON.stringify(path)) { stopped = true; break; }
            }
            assert(stopped, 'fixture exceeded the proved depth-based stopping bound');
            assert.deepEqual(path.map(r => owner[r]), expected, 'interleaved result disagrees with settled projection');
            lines.push(`example : (interleavedPass model${n} owner${n} ${ops.length} ${list(order.map(t => rank[t]))} []).headD model${n}.size = winner model${n} ${ops.length} ${list(order.map(t => rank[t]))} := interleaved_empty_head _ _ _ _`);
            const starts = [[], ...passes.slice(0, -1).map(steps => steps.at(-1).map(t => rank[t]))];
            for (const start of starts) {
                lines.push(`example : interleavedUntilStable model${n} owner${n} ${ops.length} ${list(order.map(t => rank[t]))} ${passBound} ${list(start)} = some ${list(path)} := by`,
                    `  change interleavedUntilStable model${n} owner${n} ${ops.length} ${list(order.map(t => rank[t]))} (model${n}.level ${ops.length} + 1) ${list(start)} = _`,
                    `  rw [interleaved_replay_converges model${n} owner${n} ${list(order.map(t => rank[t]))} ${ops.length} ${list(start)} descending${n} ${validPath(start)}]`,
                    '  decide');
            }
            cases.push({ vector: n, order, passBound, passes });
        }
    });
    lines.push('end Archon.InterleavedFixtures', '');
    return { lean: lines.join('\n'), cases };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const input = JSON.parse(readFileSync(new URL('../../tests/convergence/chain-successor-vectors.json', import.meta.url), 'utf8'));
    const { lean, cases } = generateInterleavedFixtures(input);
    for (const [path, result] of [['./InterleavedFixtures.lean', lean],
        ['../../tests/convergence/interleaved-cases.json', '[\n' + cases.map(c => JSON.stringify(c)).join(',\n') + '\n]\n']]) {
        const destination = new URL(path, import.meta.url);
        if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), result, 'interleaved fixtures are stale');
        else writeFileSync(destination, result);
    }
}
