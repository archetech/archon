// Bridge only: signatures/authorization remain checked by the Gatekeeper suites.
// Assign numeric IDs by ASCII canonical-CID order, not fixture index or timestamp.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = new URL('../../tests/convergence/vectors.json', import.meta.url);
const destination = new URL('./Fixtures.lean', import.meta.url);
const fixture = JSON.parse(readFileSync(source, 'utf8'));
const lines = ['-- Generated by generate-fixtures.mjs; do not edit.', 'import AgentConvergence', '', 'set_option warningAsError true', '', 'namespace Archon.Fixtures', ''];
const list = values => `[${values.join(', ')}]`;
let count = 0;
for (const [number, history] of fixture.histories.entries()) {
    const sorted = history.ids.slice().sort();
    if (new Set(sorted).size !== sorted.length) throw new Error('Expected distinct canonical CIDs');
    const rank = index => sorted.indexOf(history.ids[index]);
    const byRank = sorted.map(id => history.operations[history.ids.indexOf(id)]);
    const parents = byRank.map(op => {
        if (op.type === 'create') return 'none';
        const parent = sorted.indexOf(op.previd);
        if (parent < 0) throw new Error('Fixture predecessor is not a canonical operation ID');
        if (op.type !== 'update' || Object.keys(op.doc).some(key => key !== 'didDocumentData')) {
            throw new Error('Proof bridge only supports data-only updates');
        }
        return `some ${parent}`;
    });
    const depth = (index, seen = new Set()) => {
        if (seen.has(index)) throw new Error('Cyclic fixture');
        const nextSeen = new Set([...seen, index]);
        const children = history.operations.flatMap((op, i) => op.previd === history.ids[index] ? [i] : []);
        return children.length ? 1 + Math.max(...children.map(i => depth(i, nextSeen))) : 0;
    };
    const levels = sorted.map(id => depth(history.ids.indexOf(id)));
    lines.push(`-- ${history.registry}: finite, fixed-authorization data-only graph.`,
        `def model${number} : Model := {`,
        `  size := ${sorted.length}`,
        `  parent := fun i => (${list(parents)} : List (Option Nat))[i]?.getD none`,
        '  authorized := fun _ => true',
        `  level := fun i => (${list(levels)} : List Nat)[i]?.getD 0`, '}', '');
    const idCases = sorted.map((_, i) => `i = ${i}`).join(' ∨ ');
    lines.push(`theorem model${number}_acyclic : WellFoundedEdges model${number} := by`,
        '  intro p i h',
        `  have bound : i < ${sorted.length} := by`,
        '    simp only [eligible, Bool.and_eq_true, decide_eq_true_eq] at h',
        '    exact h.1.1',
        `  have cases : ${idCases} := by omega`,
        `  rcases cases with ${sorted.map(() => 'rfl').join(' | ')} <;> simp [eligible, model${number}] at h`,
        '  all_goals subst p; decide', '');
    for (const scenario of fixture.scenarios.filter(s => s.registry === history.registry)) {
        // The theorem excludes chain priority and foreign-anchor representations.
        if (['BTC:signet', 'foreign-anchor'].includes(scenario.transport)) continue;
        lines.push(`-- ${scenario.name}`);
        for (const row of scenario.cases) {
            const evidence = list(row.order.map(rank));
            const expected = list(row.expected.map(rank));
            lines.push(`example : history model${number} ${rank(0)} ${evidence} = ${expected} := by decide`);
            count++;
        }
        lines.push('');
    }
}
lines.push('end Archon.Fixtures', '');
const result = lines.join('\n');
if (process.argv.includes('--check')) {
    if (readFileSync(destination, 'utf8') !== result) throw new Error('Lean fixtures are stale; regenerate them');
} else {
    writeFileSync(destination, result);
}
console.log(`${count} shared signed delivery traces mapped to ${fileURLToPath(destination)}`);
