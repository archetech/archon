import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { isDeepStrictEqual } from 'node:util';
import { pathToFileURL } from 'node:url';
import { integratedAgentGraph } from '../../tests/convergence/integrated-agent-model.mjs';
const list = xs => `[${xs.join(', ')}]`;
const table = (xs, fallback) => `(fun i => ${list(xs)}.getD i (${fallback}))`;
export function generateIntegratedAgentFixtures(vectors, options = {}) {
    const namespace = options.namespace ?? 'Archon.IntegratedAgentFixtures';
    const lines = ['-- Generated by generate-integrated-agent-fixtures.mjs; do not edit.',
        'import IntegratedAgentConvergence', 'set_option warningAsError true', 'set_option maxRecDepth 10000',
        'set_option maxHeartbeats 8000000', `namespace ${namespace}`];
    vectors.forEach((v, n) => {
        const d = integratedAgentGraph(v, options.registryNames), count = v.ids.length;
        const byRank = d.ranks.map((_, i) => d.ranks.indexOf(i));
        const lookup = (xs, fallback) => table(byRank.map(i => xs[i]), fallback);
        const atoms = [...new Set([{}, { id: v.did }, d.registration, ...d.fullDocuments,
            ...v.operations.flatMap(op => Object.values(op.doc ?? {}))].map(value => JSON.stringify(value)))].sort();
        const token = value => { const i = atoms.indexOf(JSON.stringify(value)); assert(i >= 0); return i; };
        const g = `graph${n}`, patch = `patch${n}`, r = `receipts${n}`, a = `anchors${n}`, m = `model${n}`;
        lines.push(`def atoms${n} : Nat → String := ${table(atoms.map(JSON.stringify), '""')}`);
        const methods = atoms.map(atom => {
            const doc = d.fullDocuments.find(value => JSON.stringify(value) === atom);
            return list((doc?.verificationMethod ?? []).map(method => {
                const name = method.id.startsWith('#') ? v.did + method.id : method.id;
                const key = v.keys.findIndex(key => isDeepStrictEqual(key, method.publicKeyJwk));
                assert(key >= 0 && d.methodNames.includes(name));
                return `⟨${d.methodNames.indexOf(name)}, ${key}⟩`;
            }));
        });
        lines.push(`def methods${n} : Nat → List VerificationMethod := ${table(methods, '[]')}`,
            `def documents${n} : Nat → Nat := ${table(d.fullDocuments.map(token), token({}))}`,
            `def ${g} : DocumentGraph := {`, `  size := ${count}`, `  root := ${d.root}`, `  initialDocument := ${d.root}`,
            `  parent := ${lookup(d.parents.map(p => p === null ? 'none' : 'some ' + d.ranks[p]), 'none')}`,
            `  depth := ${lookup(d.depths, '0')}`,
            `  action := ${lookup(d.actions.map(x => x === 'keep' ? 'AgentAction.keep' : x === 'delete' ? 'AgentAction.deactivate' : 'AgentAction.rotate ' + x), 'AgentAction.keep')}`,
            `  documents := ${table(d.documents.map(doc => list(doc.map(x => '⟨' + x.id + ', ' + x.key + '⟩'))), '[]')}`,
            `  named := ${lookup(d.named, '0')}`,
            `  signatureValid := fun i k => (${lookup(v.signatureValid.map(list), '[]')}) i |>.getD k false`, '}',
            `theorem methods_agree${n} : ∀ i, methods${n} (documents${n} i) = ${g}.documents i := by`, '  intro i');
        for (let i = 0; i < count; i++) lines.push('  '.repeat(i + 1) + 'cases i with', '  '.repeat(i + 1) + '| zero => rfl', '  '.repeat(i + 1) + '| succ i =>');
        lines.push('  '.repeat(count + 1) + 'rfl',
            `theorem ordered${n} : AncestryOrdered (documentAgent ${g}) := by`, '  intro i p parent', `  by_cases bound : i < ${count}`,
            `  · have cases : ${byRank.map((_, i) => 'i = ' + i).join(' ∨ ')} := by omega`,
            `    rcases cases with ${byRank.map(() => 'rfl').join(' | ')} <;> simp [documentAgent, ${g}] at parent`,
            '    all_goals subst p; decide', `  · have outside : ${count} ≤ i := by omega`,
            `    simp only [documentAgent, ${g}] at parent`,
            '    rw [List.getD_eq_getElem?_getD, List.getElem?_eq_none (by simpa using outside)] at parent', '    simp at parent',
            `theorem bounded${n} : DepthBounded (documentAgent ${g}) := by`, '  intro i bound', `  have small : i < ${count} := bound`,
            `  have checked : ∀ i : Fin ${count}, (documentAgent ${g}).depth i.val < (documentAgent ${g}).size := by decide`, '  exact checked ⟨i, small⟩');
        lines.push(`theorem parents${n} : AgentParentBounded ${g} := by`, '  intro i p bound parent',
            `  have small : i < ${count} := bound`,
            `  have cases : ${byRank.map((_, i) => 'i = ' + i).join(' ∨ ')} := by omega`,
            `  rcases cases with ${byRank.map(() => 'rfl').join(' | ')} <;> simp [${g}] at parent`,
            '  all_goals subst p; decide');
        const patches = v.operations.map(op => '⟨' + ['didDocumentData', 'didDocumentRegistration'].map(key => Object.hasOwn(op.doc ?? {}, key) ? 'some ' + token(op.doc[key]) : 'none').join(', ') + '⟩');
        const registries = atoms.map(atom => d.names.indexOf(JSON.parse(atom).registry));
        lines.push(`def ${patch} : Nat → ComponentPatch Nat Nat := ${lookup(patches, '⟨none, none⟩')}`,
            `def registry${n} : Nat → Nat := ${table(registries.map(i => i < 0 ? d.names.length : i), d.names.length)}`,
            `def ${r} : RegistryReceipts := {`, `  size := ${d.anchors.length}`,
            `  owner := ${table(d.anchors.map(i => d.ranks[d.owners[i]]), count)}`,
            `  registry := ${table(d.anchors.map(i => d.names.indexOf(v.events[i].registry)), d.names.length)}`,
            `  chain := ${table(d.names.map(name => !['local', 'hyperswarm', 'pin'].includes(name)), 'false')}`,
            '  accepted := fun _ => true', '}',
            `abbrev ${a} := componentAnchors ${g} ${patch} registry${n} ${token(d.registration)} ${r}`,
            `abbrev ${m} := componentEvents ${g} ${a}`);
        const rg = `(componentRegistry ${g} ${patch} registry${n} ${token(d.registration)})`;
        lines.push(`def positions${n} : Nat → List Nat := ${table(d.anchors.map(i => list(v.events[i].ordinal)), '[]')}`,
            `theorem ranks${n} : RegistryCidRanks ${rg} ${r} positions${n} := by`,
            '  intro x y xv yv same', `  have xb : x < ${d.anchors.length} := eligible_lt _ _ _ xv`,
            `  have yb : y < ${d.anchors.length} := eligible_lt _ _ _ yv`,
            `  have checked : ∀ x y : Fin ${d.anchors.length},`,
            `      eligible (registryAnchors ${rg} ${r}) (${r}.owner x.val) x.val = true →`,
            `      eligible (registryAnchors ${rg} ${r}) (${r}.owner y.val) y.val = true →`,
            `      ${r}.registry x.val = ${r}.registry y.val →`,
            `      (x.val < y.val ↔ compare (positions${n} x.val) (positions${n} y.val) = .lt ∨`,
            `        (compare (positions${n} x.val) (positions${n} y.val) = .eq ∧ ${r}.owner x.val < ${r}.owner y.val)) := by decide`,
            '  exact checked ⟨x, xb⟩ ⟨y, yb⟩ xv yv same');
        lines.push(`def operationTime${n} : Nat → Int := ${lookup(v.operations.map(op => Date.parse(op.proof.created)), '0')}`,
            `def chainFacts${n} : Nat → ChainReceiptView := ${table(d.anchors.map(i => {
                const e = v.events[i];
                return `⟨${d.names.indexOf(e.registry)}, ${list(e.ordinal)}, ${Date.parse(e.time)}, ${!!e.registration}⟩`;
            }), '⟨0, [], 0, false⟩')}`);
        d.scenarios.forEach((scenario, s) => {
            const receipts = list(scenario.anchorSet), operations = list(scenario.retained.map(i => d.ranks[i]));
            const covered = `covered${n}_${s}`;
            lines.push(`theorem ${covered} : ∀ i ∈ (${receipts} : List Nat), eligible ${a} (chainOwner ${a} i) i = true → chainOwner ${a} i ∈ (${operations} : List Nat) := by`,
                '  intro i member ok', `  have bound : i < ${d.anchors.length} := eligible_lt _ _ _ ok`,
                `  have checked : ∀ i : Fin ${d.anchors.length}, i.val ∈ (${receipts} : List Nat) → eligible ${a} (chainOwner ${a} i.val) i.val = true → chainOwner ${a} i.val ∈ (${operations} : List Nat) := by decide`,
                '  exact checked ⟨i, bound⟩ member ok');
            scenario.orders.forEach((order, k) => {
                // Normalization contributes a provisional representative even for
                // chain-only retained operations. Ineligible anchors are filtered.
                const records = order.flatMap(i => {
                    const owner = d.owners[i], provisional = d.anchors.length + d.ranks[owner];
                    const anchored = d.rank[i] < d.anchors.length && v.events[i].registry === d.expected[owner] && d.states[owner] !== null;
                    return [...(anchored ? [`⟨${d.rank[i]}, true, ${i + k * 1000}⟩`] : []), `⟨${provisional}, ${v.events[i].registry === d.expected[owner]}, ${i + k * 1000}⟩`];
                });
                const name = `records${n}_${s}_${k}`, represented = `represented${n}_${s}_${k}`;
                const sources = `sources${n}_${s}_${k}`;
                lines.push(`def ${sources} : List (AgentSourceReceipt Nat) := ${list(order.map(i => {
                    const e = v.events[i];
                    return `⟨⟨${d.ranks[d.owners[i]]}, ${d.names.indexOf(e.registry)}, ${d.rank[i] < d.anchors.length ? 'some ' + d.rank[i] : 'none'}⟩, ${i + k * 1000}⟩`;
                }))}`);
                lines.push(`def ${name} : List (EventRecord Nat) := ${list(records)}`,
                    `theorem ${represented} : ∀ i, i ∈ recordIds ${name} ↔ i ∈ componentEventEvidence ${a} ${receipts} ${operations} := by`,
                    '  intro i',
                    `  have normalized : componentEventEvidence ${a} ${receipts} ${operations} = ${list([...scenario.anchorSet.filter(rank => { const i = d.anchors[rank]; return v.events[i].registry === d.expected[d.owners[i]] && d.states[d.owners[i]] !== null; }), ...scenario.retained.map(i => d.anchors.length + d.ranks[i])])} := by decide`,
                    `  rw [normalized]`, `  simp [recordIds, ${name}] <;> omega`);

                lines.push(`example : (normalizeAgentSources ${a} (expectedRegistry ${rg}) ${sources}).map (fun record => (⟨record.opid, record.expected, record.payload.bookkeeping⟩ : EventRecord Nat)) = ${name} := by decide`);
                const initial = `⟨.active ${g}.initialDocument, ${token({})}, ${token(d.registration)}⟩`;
                const expected = list(scenario.expected.map(i => d.ranks[i]));
                const result = `(${token(scenario.components.didDocument)}, ${token(scenario.components.didDocumentData)}, ${token(scenario.components.didDocumentRegistration)})`;
                lines.push(`example : ∃ result final,`,
                    `    stopWhenStable (rankedPass ${m} (chainOwner ${a}) ${g}.root ${name}) (${m}.level ${g}.root + 2) [] = some result ∧`,
                    `    rankedPass ${m} (chainOwner ${a}) ${g}.root ${name} result = result ∧`,
                    `    chainReplay (agentModel (documentAgent ${g})) ${a} ${receipts} ${g}.root ${operations} = some (${g}.root :: (recordIds result).map (chainOwner ${a})) ∧`,
                    `    runComponents (decodedComponentGraph ${g} documents${n} methods${n}) ${patch} ${token({})} ${initial} ((recordIds result).map (chainOwner ${a})) = some final :=`,
                    `  component_full_replay ${g} documents${n} methods${n} methods_agree${n} ${patch} registry${n} ${token(d.registration)} ${token({})} ${token({})} ${r} ordered${n} bounded${n} (by decide) (by decide) ${receipts} ${operations} ${name} [] ${covered} (by decide) ${represented} (.nil _)`,
                    `example : (stopWhenStable (rankedPass ${m} (chainOwner ${a}) ${g}.root ${name}) (${m}.level ${g}.root + 2) []).map (fun records => (${g}.root :: (recordIds records).map (chainOwner ${a}), (runComponents ${g} ${patch} ${token({})} ${initial} ((recordIds records).map (chainOwner ${a}))).map (componentResult documents${n} ${token({ id: v.did })}))) = some (${expected}, some ${result}) := by decide`);
                const cold = `(coldComponentEvents ${g} ${a})`;
                lines.push(`example : ∃ result final,`,
                    `    stopWhenStable (rankedPass ${cold} (chainOwner ${a}) ${g}.size ${name}) (${cold}.size + 3) [] = some result ∧`,
                    `    rankedPass ${cold} (chainOwner ${a}) ${g}.size ${name} result = result ∧`,
                    `    ((recordIds result).map (chainOwner ${a})).head? = some ${g}.root ∧`,
                    `    runComponents ${g} ${patch} ${token({})} ${initial} (((recordIds result).map (chainOwner ${a})).drop 1) = some final :=`,
                    `  component_cold_full_replay ${g} ${patch} registry${n} ${token(d.registration)} ${token({})} ${token({})} ${r} ordered${n} bounded${n} parents${n} (by decide) (by decide) ${name} (by decide)`,
                    `example : (stopWhenStable (rankedPass ${cold} (chainOwner ${a}) ${g}.size ${name}) (${cold}.size + 3) []).map (fun records => ((recordIds records).map (chainOwner ${a}), (runComponents ${g} ${patch} ${token({})} ${initial} (((recordIds records).map (chainOwner ${a})).drop 1)).map (componentResult documents${n} ${token({ id: v.did })}))) = some (${expected}, some ${result}) := by decide`);
                lines.push(`example := integrated_agent_execution ${g} ${patch} registry${n} ${token(d.registration)} ${token({})} ${token({})} ${r} ordered${n} bounded${n} parents${n} (by decide) (by decide) ${sources} (by decide)`);
                const view = `(agentReceiptView ${a} (expectedRegistry ${rg}) operationTime${n} chainFacts${n})`;
                const receiptResult = list(scenario.receiptView.map(entry => {
                    const owner = v.ids.indexOf(entry.operation), c = entry.cutoff;
                    const cutoff = c.kind === 'unconfirmed' ? 'ReceiptCutoffView.unconfirmed'
                        : c.kind === 'chain' ? `ReceiptCutoffView.chain ⟨${d.names.indexOf(c.registry)}, ${list(c.ordinal)}, ${c.time}, ${c.registration}⟩`
                            : `ReceiptCutoffView.unanchored (some ${d.names.indexOf(c.registry)}) ${c.time}`;
                    return `⟨${d.ranks[owner]}, ${entry.matching}, ${cutoff}⟩`;
                }));
                lines.push(`example : (stopWhenStable (rankedPass ${cold} (chainOwner ${a}) ${g}.size ${name}) (${cold}.size + 3) []).map (fun records => confirmedReceiptView (records.map ${view})) = some ${receiptResult} := by decide`);
                if (k) {
                    const first = `sources${n}_${s}_0`;
                    lines.push(`theorem source_agrees${n}_${s}_${k} : SameAgentSources ${sources} ${first} := by`,
                        `  exact same_sources_of_check ${sources} ${first} (by decide)`,
                        `example := integrated_agent_convergence ${g} ${patch} registry${n} ${token(d.registration)} ${token({})} ${token({})} ${r} operationTime${n} chainFacts${n} ordered${n} bounded${n} ${sources} ${first} source_agrees${n}_${s}_${k}`);
                }
            });
        });
    });
    lines.push(`end ${namespace}`, '');
    return lines.join('\n');
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const vectors = JSON.parse(readFileSync(new URL('../../tests/convergence/integrated-agent-vectors.json', import.meta.url), 'utf8'));
    const output = generateIntegratedAgentFixtures(vectors);
    const target = new URL('./IntegratedAgentFixtures.lean', import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8'), output);
    else writeFileSync(target, output);
}
