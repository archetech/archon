import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { documentGraph, documentStates } from '../../tests/convergence/document-model.mjs';
import { comparePositions } from './generate-chain-anchor-fixtures.mjs';
const list = xs => `[${xs.join(', ')}]`;

export function generateChainDocumentFixtures(vectors) {
    const lines = ['-- Generated by generate-chain-document-fixtures.mjs; do not edit.', 'import ChainDocuments',
        'set_option warningAsError true', 'set_option maxRecDepth 10000', 'set_option maxHeartbeats 4000000',
        'namespace Archon.ChainDocumentFixtures'];
    const cases = [];
    vectors.forEach((v, n) => {
        const d = documentGraph(v, false, 'BTC:signet');
        const states = documentStates(v, d);
        assert.deepEqual(states, v.states, 'state oracle disagrees with document ancestry');
        const { ranks, root } = d, count = ranks.length;
        const byRank = ranks.map((_, i) => ranks.indexOf(i));
        const lookup = (values, fallback) => `(fun i => ${list(byRank.map(i => values[i]))}.getD i (${fallback}))`;
        const table = (values, fallback) => `(fun i => ${list(values)}.getD i (${fallback}))`;
        const g = `graph${n}`, a = `anchors${n}`, owner = `owner${n}`, m = `raw${n}`, c = `compiled${n}`, priority = `priority${n}`;
        const owners = v.events.map(e => {
            assert(['hyperswarm', 'BTC:signet'].includes(e.registry), 'foreign registry outside fixture domain');
            const index = v.operations.findIndex(op => isDeepStrictEqual(op, e.operation));
            assert(index >= 0, 'event must match a signed operation');
            return ranks[index];
        });
        const anchors = v.events.flatMap((e, i) => e.registry === 'BTC:signet' ? [i] : []);
        for (const t of anchors) assert(Array.isArray(v.events[t].ordinal) && v.events[t].ordinal.length && v.events[t].ordinal.every(x => Number.isSafeInteger(x) && x >= 0), 'complete ordinal required');
        anchors.sort((x, y) => comparePositions(v.events[x].ordinal, v.events[y].ordinal));
        for (let i = 1; i < anchors.length; i++) assert(comparePositions(v.events[anchors[i - 1]].ordinal, v.events[anchors[i]].ordinal) < 0, 'tied ordinals excluded');
        const anchorRank = new Map(anchors.map((t, i) => [t, i]));
        const rank = v.events.map((_, t) => anchorRank.get(t) ?? anchors.length + owners[t]);
        assert.equal(new Set(rank).size, rank.length, 'one provisional representation per operation required');
        const token = new Map(rank.map((r, t) => [r, t]));
        const ownerTable = [...anchors.map(t => owners[t]), ...byRank.map((_, i) => i)];
        const predecessor = ownerTable.map(op => d.parents[byRank[op]] === null ? null : ranks[d.parents[byRank[op]]]);
        const authorized = ownerTable.map(op => states[byRank[op]] !== null);
        const size = ownerTable.length;
        const evidence = rank.slice().sort((x, y) => x - y), selected = byRank.map((_, i) => i);
        assert.equal(owners[v.seed], root, 'seed must be genesis');
        assert.equal(v.events[v.seed].registry, 'BTC:signet', 'seed must be anchored');
        assert.equal(rank[v.seed], Math.min(...rank.filter((_, t) => owners[t] === root)), 'seed must be preferred genesis');
        const choose = op => Math.min(...rank.filter((_, t) => owners[t] === op));
        const final = v.expected.slice(1).map(i => choose(ranks[i]));
        assert.equal(ranks[v.expected[0]], root);
        const finalState = states[v.expected.at(-1)];
        assert(finalState !== null, 'expected tip is unauthorized');
        const finalLean = finalState === 'deleted' ? 'AgentState.deleted' : `(AgentState.active ${finalState})`;
        lines.push(`def ${g} : DocumentGraph := {`, `  size := ${count}`, `  root := ${root}`, `  initialDocument := ${root}`,
            `  parent := ${lookup(d.parents.map(p => p === null ? 'none' : 'some ' + ranks[p]), 'none')}`,
            `  depth := ${lookup(d.depths, '0')}`,
            `  action := ${lookup(d.actions.map(x => x === 'keep' ? 'AgentAction.keep' : x === 'delete' ? 'AgentAction.deactivate' : 'AgentAction.rotate ' + x), 'AgentAction.keep')}`,
            `  documents := ${table(d.documents.map(doc => list(doc.map(x => '⟨' + x.id + ', ' + x.key + '⟩'))), '[]')}`,
            `  named := ${lookup(d.named, '0')}`,
            `  signatureValid := fun i k => (${lookup(v.signatureValid.map(list), '[]')}) i |>.getD k false`, '}',
            `theorem ordered${n} : AncestryOrdered (documentAgent ${g}) := by`, '  intro i p parent', `  by_cases bound : i < ${count}`,
            `  · have cases : ${byRank.map((_, i) => 'i = ' + i).join(' ∨ ')} := by omega`,
            `    rcases cases with ${byRank.map(() => 'rfl').join(' | ')} <;> simp [documentAgent, ${g}] at parent`,
            '    all_goals subst p; decide', `  · have outside : ${count} ≤ i := by omega`,
            `    simp only [documentAgent, ${g}] at parent`,
            '    rw [List.getD_eq_getElem?_getD, List.getElem?_eq_none (by simpa using outside)] at parent', '    simp at parent',
            `theorem bounded${n} : DepthBounded (documentAgent ${g}) := by`, '  intro i bound', `  have small : i < ${count} := bound`,
            `  have checked : ∀ i : Fin ${count}, (documentAgent ${g}).depth i.val < (documentAgent ${g}).size := by decide`, '  exact checked ⟨i, small⟩',
            `def ${a} : AnchorModel := ⟨${anchors.length}, ${table(anchors.map(t => 'some ' + owners[t]), 'none')}, fun i => (agentModel (documentAgent ${g})).authorized ((${table(anchors.map(t => owners[t]), '0')}) i), fun _ => 0⟩`,
            `abbrev ${owner} := chainOwner ${a}`,
            `abbrev ${m} := documentEvents ${g} ${size} ${owner} (fun _ => true)`,
            `abbrev ${priority} := chainPriority ${a} ${list(anchors.map((_, i) => i))}`,
            `abbrev ${c} := chainGraph (agentModel (documentAgent ${g})) ${a} ${list(anchors.map((_, i) => i))}`,
            `def evidence${n} : List Nat := ${list(evidence)}`,
            `def selected${n} : List Nat := ${list(selected)}.map ${priority}`,
            `theorem projection${n} : PriorityProjection ${m} ${c} ${owner} ${priority} evidence${n} selected${n} ${g}.size := by`, '  constructor', '  · rfl');
        const fields = [
            [`i.val ∈ evidence${n} → eligible ${m} p.val i.val = true`, `${priority} (${owner} i.val) ∈ selected${n} ∧ eligible ${c} (${priority} p.val) (${priority} (${owner} i.val)) = true ∧ ${priority} (${owner} i.val) ≤ i.val`],
            [`i.val ∈ selected${n} → eligible ${c} (${priority} p.val) i.val = true`, `i.val ∈ evidence${n} ∧ eligible ${m} p.val i.val = true`],
            [`i.val ∈ selected${n} → eligible ${c} (${priority} p.val) i.val = true`, `i.val = ${priority} (${owner} i.val) ∧ ${owner} i.val < ${count}`],
        ];
        for (const [premise, conclusion] of fields) lines.push('  · intro p scope i member valid',
            `    have bound : i < ${size} := eligible_lt _ _ _ valid`,
            `    have checked : ∀ p : Fin ${count}, ∀ i : Fin ${size}, ${premise} → ${conclusion} := by decide`,
            '    exact checked ⟨p, scope⟩ ⟨i, bound⟩ member valid');
        lines.push(`theorem acyclic${n} : WellFoundedEdges ${c} := by`,
            '  intro p i valid', `  have bound : i < ${size} := eligible_lt _ _ _ valid`,
            `  have parent := eligible_parent ${c} p i valid`,
            `  have range : ∀ i : Fin ${size}, ((${c}.parent i.val).map (fun p => decide (p < ${size}))).getD true = true := by decide`,
            `  have pb : p < ${size} := by`,
            '    have h := range ⟨i, bound⟩', '    simpa [parent] using h',
            `  have checked : ∀ p : Fin ${size}, ∀ i : Fin ${size}, eligible ${c} p.val i.val = true → ${c}.level i.val < ${c}.level p.val := by decide`,
            '  exact checked ⟨p, pb⟩ ⟨i, bound⟩ valid');
        lines.push(`theorem canonical${n} : (interleavedUntilStable ${m} ${owner} ${root} evidence${n} (${m}.level ${root} + 1) []).map (fun path => (path, runAgent (documentAgent ${g}) (.active ${root}) (path.map ${owner}))) = some (${list(final)}, some ${finalLean}) := by`,
            `  obtain ⟨result, final, replay, cold, decoded, _, _⟩ := interleaved_document_priority_cold ${g} ${size} ${owner} ${priority} (fun _ => true) ${c} ordered${n} bounded${n} (by decide) (by decide) evidence${n} selected${n} [] projection${n} (.nil _) (by decide) acyclic${n} (by decide) (by decide) (chain_priority_owner ${a} ${list(anchors.map((_, i) => i))} ${root})`,
            `  have expected : replayCold ${c} (${priority} ${root}) selected${n} = some (${priority} ${root} :: ${list(final)}) := by`,
            `    rw [cold_replay_converges ${c} (${priority} ${root}) selected${n} acyclic${n} (by decide) (by decide)]`,
            '    decide',
            `  have selected : result = ${list(final)} := (List.cons.inj (Option.some.inj (cold.symm.trans expected))).2`,
            `  change interleavedUntilStable ${m} ${owner} ${root} evidence${n} (${m}.level ${root} + 1) [] = some result at replay`,
            `  change (replayCold ${c} (${priority} ${root}) selected${n}).map (List.map ${owner}) = some (${root} :: result.map ${owner}) at decoded`,
            `  have decodedExpected : (replayCold ${c} (${priority} ${root}) selected${n}).map (List.map ${owner}) = some ${list(v.expected.map(i => ranks[i]))} := by`,
            '    rw [decoded, selected]', '    decide',
            '  rw [replay, Option.map_some, selected]', '  decide');
        const insert = (p, incoming, path) => {
            const eligible = authorized[incoming] && predecessor[incoming] === p;
            if (!path.length) return eligible ? [incoming] : [];
            const [current, ...rest] = path;
            if (eligible) {
                if (ownerTable[current] === ownerTable[incoming]) return [Math.min(current, incoming), ...rest];
                return incoming < current ? [incoming] : path;
            }
            return [current, ...insert(ownerTable[current], incoming, rest)];
        };
        const passBound = count - d.depths[byRank[root]] + 1;
        assert.equal(new Set(v.orders.map(order => JSON.stringify(order))).size, v.orders.length, 'duplicate delivery orders');
        for (const order of v.orders) {
            assert(order.every(t => Number.isInteger(t) && v.events[t]), 'unknown event token');
            assert.equal(new Set(order).size, v.events.length, 'complete evidence required');
            const delivery = list(order.map(t => rank[t]));
            let path = [], stopped = false;
            const passes = [];
            for (let pass = 0; pass < passBound; pass++) {
                const before = path, steps = [];
                for (const t of order) {
                    const after = insert(root, rank[t], path);
                    lines.push(`example : interleavedInsert ${m} ${owner} ${root} ${rank[t]} ${list(path)} = ${list(after)} := by decide`);
                    path = after;
                    steps.push([v.seed, ...path.map(r => token.get(r))]);
                }
                lines.push(`example : interleavedPass ${m} ${owner} ${root} ${delivery} ${list(before)} = ${list(path)} := by decide`);
                passes.push(steps);
                if (JSON.stringify(before) === JSON.stringify(path)) { stopped = true; break; }
            }
            assert(stopped, 'exceeded theorem stopping bound');
            assert.deepEqual(path, final, 'trace disagrees with expected ranked path');
            lines.push(`example : (interleavedUntilStable ${m} ${owner} ${root} ${delivery} (${m}.level ${root} + 1) []).map (fun path => (path, runAgent (documentAgent ${g}) (.active ${root}) (path.map ${owner}))) = some (${list(final)}, some ${finalLean}) := by`,
                `  rw [interleaved_replay_same_evidence ${m} ${owner} ${delivery} evidence${n} ${root} [] [] (document_events_descending ${g} ${size} ${owner} (fun _ => true) ordered${n} bounded${n}) (.nil _) (.nil _) (bounded_membership_agrees ${size} _ _ (by decide) (by decide) (by decide))]`, `  exact canonical${n}`);
            cases.push({ vector: n, order, passBound, passes });
        }
    });
    lines.push('end Archon.ChainDocumentFixtures', '');
    return { lean: lines.join('\n'), cases };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const input = JSON.parse(readFileSync(new URL('../../tests/convergence/chain-document-vectors.json', import.meta.url), 'utf8'));
    const { lean, cases } = generateChainDocumentFixtures(input);
    for (const [path, result] of [['./ChainDocumentFixtures.lean', lean], ['../../tests/convergence/chain-document-cases.json', '[\n' + cases.map(c => JSON.stringify(c)).join(',\n') + '\n]\n']]) {
        const destination = new URL(path, import.meta.url);
        if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), result, 'chain document fixtures are stale');
        else writeFileSync(destination, result);
    }
}
