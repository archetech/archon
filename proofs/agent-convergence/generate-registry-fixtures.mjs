import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { migrationProjection } from '../../tests/convergence/migration-model.mjs';
import { comparePositions } from './generate-chain-anchor-fixtures.mjs';
const list = xs => `[${xs.join(', ')}]`;

export function generateRegistryFixtures(vectors) {
    const lines = ['-- Generated by generate-registry-fixtures.mjs; do not edit.', 'import RegistryPriority',
        'set_option warningAsError true', 'namespace Archon.RegistryFixtures'];
    let orders = 0, prefixes = 0, receipts = 0, anchors = 0, warm = 0, replays = 0, comparisons = 0;
    vectors.forEach((v, n) => {
        const projection = migrationProjection(v);
        assert.deepEqual(projection.path, v.expected, 'expected path disagrees with audit projection');
        assert.equal(projection.registry, v.expectedRegistry, 'expected registry disagrees with audit projection');
        const ids = [...v.ids].sort(), ranks = v.ids.map(id => ids.indexOf(id));
        const ops = ids.map(id => v.operations[v.ids.indexOf(id)]);
        const root = ops.findIndex(op => op.type === 'create');
        const parents = ops.map((op, i) => i === root ? null : ids.indexOf(op.previd));
        const names = [...new Set([ops[root].registration.registry,
            ...ops.flatMap(op => op.doc?.didDocumentRegistration ? [op.doc.didDocumentRegistration.registry] : []),
            ...v.events.map(e => e.registry)])].sort();
        const initial = names.indexOf(ops[root].registration.registry);
        const changes = ops.map(op => op.doc?.didDocumentRegistration?.registry);
        const ancestors = i => i === root ? [] : [...ancestors(parents[i]), i];
        const depth = ops.map((_, i) => ancestors(i).length);
        const g = `graph${n}`, size = ops.length;
        const table = (xs, fallback) => `(fun i => ${list(xs)}.getD i (${fallback}))`;
        lines.push(`-- Registry names: ${names.join(', ')}`, `def ${g} : RegistryGraph := {`,
            `  size := ${size}`, `  root := ${root}`, `  initial := ${initial}`,
            `  parent := ${table(parents.map(p => p === null ? 'none' : 'some ' + p), 'none')}`,
            `  depth := ${table(depth, '0')}`,
            `  change := ${table(changes.map(r => r === undefined ? 'none' : 'some ' + names.indexOf(r)), 'none')}`, '}',
            `theorem ordered${n} : RegistryOrdered ${g} := by`, '  intro i p parent', `  by_cases bound : i < ${size}`,
            `  · have cases : ${ops.map((_, i) => 'i = ' + i).join(' ∨ ')} := by omega`,
            `    rcases cases with ${ops.map(() => 'rfl').join(' | ')} <;> simp [${g}] at parent`,
            '    all_goals subst p; decide', `  · have outside : ${size} ≤ i := by omega`,
            `    simp only [${g}] at parent`,
            '    rw [List.getD_eq_getElem?_getD, List.getElem?_eq_none (by simpa using outside)] at parent', '    simp at parent',
            `example : expectedRegistry ${g} ${root} = some ${initial} := by decide`);
        const valid = path => path.reduceRight(tail => `(.cons (by decide) (by decide) ${tail})`, '(.nil _)');
        const owners = v.events.map(e => ranks[v.operations.findIndex(op => isDeepStrictEqual(e.operation, op))]);
        const receiptOrder = v.events.map((_, t) => t).sort((a, b) => owners[a] - owners[b] || names.indexOf(v.events[a].registry) - names.indexOf(v.events[b].registry));
        for (const t of receiptOrder) {
            const event = v.events[t];
            const expected = projection.expectedRegistries[v.ids.indexOf(ids[owners[t]])];
            const matches = event.registry === expected, registry = names.indexOf(event.registry);
            if (owners[t] === root) {
                lines.push(`example : receiptRegistryMatches ${g} ${owners[t]} ${registry} = ${matches} := by decide`);
            } else {
                const path = ancestors(parents[owners[t]]);
                const theorem = `receipt_registry_after_prefix ${g} ordered${n} (by decide) (by decide) ${list(ops.map((_, i) => i))} ${list(path)} ${valid(path)} ${owners[t]} ${registry} (by decide) (by decide)`;
                lines.push(`example : receiptRegistryMatches ${g} ${owners[t]} ${registry} = ${matches} := by`);
                if (matches) lines.push(`  exact (${theorem}).mpr (by decide)`);
                else lines.push('  apply Bool.eq_false_iff.mpr', '  intro matched',
                    `  have different : ${registry} ≠ registryFold ${g} ${g}.initial ${list(path)} := by decide`,
                    `  exact different ((${theorem}).mp matched)`);
            }
            receipts++;
        }
        // Registry blocks provide an arbitrary cross-chain layout. Only ordinal
        // order inside a block is meaningful; no theorem compares chain heights
        // between registries. Include wrong-chain and unanchored receipts so the
        // Lean filter, rather than this projection, excludes them.
        for (const event of v.events) assert(Array.isArray(event.ordinal) && event.ordinal.length
            && event.ordinal.every(x => Number.isSafeInteger(x) && x >= 0), 'complete integer ordinal required');
        const ranked = v.events.map((_, i) => i).sort((a, b) =>
            names.indexOf(v.events[a].registry) - names.indexOf(v.events[b].registry)
            || comparePositions(v.events[a].ordinal, v.events[b].ordinal) || owners[a] - owners[b]);
        const receiptRanks = v.events.map((_, i) => ranked.indexOf(i));
        const chain = name => !['local', 'hyperswarm', 'pin'].includes(name);
        for (let i = 1; i < ranked.length; i++) {
            const a = ranked[i - 1], b = ranked[i];
            assert(v.events[a].registry !== v.events[b].registry || owners[a] !== owners[b]
                || comparePositions(v.events[a].ordinal, v.events[b].ordinal) !== 0, 'tied operation receipts outside bridge domain');
        }
        const r = `receipts${n}`, model = `anchors${n}`, count = ranked.length;
        lines.push(`def ${r} : RegistryReceipts := {`, `  size := ${count}`,
            `  owner := ${table(ranked.map(t => owners[t]), size)}`,
            `  registry := ${table(ranked.map(t => names.indexOf(v.events[t].registry)), names.length)}`,
            `  chain := ${table(names.map(name => String(chain(name))), 'false')}`,
            `  accepted := fun i => decide (i < ${count})`, '}',
            `def ${model} := registryAnchors ${g} ${r}`);
        const matches = (op, t) => owners[t] === op && chain(v.events[t].registry)
            && v.events[t].registry === projection.expectedRegistries[v.ids.indexOf(ids[op])];
        const preferred = ops.map((_, op) => ranked.findIndex(t => matches(op, t)));
        assert(preferred.every(i => i >= 0), 'matching chain anchor required');
        assert.deepEqual(projection.path.map(i => ranked[preferred[ranks[i]]]), v.expectedEvents,
            'expected receipts disagree with predecessor-registry anchor selection');
        for (let op = 0; op < size; op++) {
            for (const t of ranked) {
                if (owners[t] !== op || op === root) continue;
                const path = ancestors(parents[op]);
                lines.push(`example : eligible ${model} ${op} ${receiptRanks[t]} = ${matches(op, t)} := by`,
                    `  have h := registry_anchor_after_prefix ${g} ${r} ordered${n} (by decide) (by decide) ${list(ops.map((_, i) => i))} ${list(path)} ${valid(path)} ${op} ${receiptRanks[t]} (by decide) (by decide)`);
                if (matches(op, t)) lines.push('  exact h.mpr (by decide)');
                else lines.push('  apply Bool.eq_false_iff.mpr', '  intro accepted', '  have impossible := h.mp accepted', '  revert impossible', '  decide');
            }
            for (let sibling = op + 1; sibling < size; sibling++) {
                if (parents[op] === null || parents[op] !== parents[sibling]) continue;
                lines.push(`example : expectedRegistry ${g} ${op} = expectedRegistry ${g} ${sibling} :=`,
                    `  siblings_expected_registry ${g} (by decide) ${op} ${sibling} ${parents[op]} (by decide) (by decide)`,
                    `example : ${r}.registry ${preferred[op]} = ${r}.registry ${preferred[sibling]} :=`,
                    `  sibling_anchors_same_registry ${g} ${r} (by decide) ${op} ${sibling} ${parents[op]} ${preferred[op]} ${preferred[sibling]} (by decide) (by decide) (by decide) (by decide)`);
            }
        }
        const all = list(ops.map((_, i) => i)), canonical = list(ranked.map((_, i) => i));
        const compiled = `compiled${n}`;
        lines.push(`def positions${n} : Nat → List Nat := ${table(ranked.map(t => list(v.events[t].ordinal)), '[]')}`,
            `theorem ordinalRanks${n} : RegistryOrdinalRanks ${g} ${r} positions${n} := by`,
            '  intro x y xv yv same',
            `  have xb : x < ${count} := eligible_lt _ _ _ xv`,
            `  have yb : y < ${count} := eligible_lt _ _ _ yv`,
            `  have finite : ∀ x y : Fin ${count},`,
            `      eligible ${model} (${r}.owner x.val) x.val = true →`,
            `      eligible ${model} (${r}.owner y.val) y.val = true →`,
            `      ${r}.registry x.val = ${r}.registry y.val →`,
            `      (x.val < y.val ↔ compare (positions${n} x.val) (positions${n} y.val) = .lt) := by decide`,
            '  exact finite ⟨x, xb⟩ ⟨y, yb⟩ xv yv same',
            `abbrev ${compiled} := chainGraph (registryModel ${g}) ${model} ${canonical}`,
            `theorem depthBound${n} : ∀ i, i < ${g}.size → ${g}.depth i < ${g}.size := by`,
            `  have finite : ∀ i : Fin ${size}, ${g}.depth i.val < ${g}.size := by decide`,
            '  intro i bound', '  exact finite ⟨i, bound⟩',
            `theorem acyclic${n} : WellFoundedEdges ${compiled} :=`,
            `  chain_graph_acyclic _ _ _ (registry_model_acyclic ${g} ordered${n} depthBound${n})`,
            `theorem settled${n} : registryReplay ${g} ${r} ${canonical} ${all} = some ${list(v.expected.map(i => ranks[i]))} := by`,
            `  change chainReplay (registryModel ${g}) ${model} ${canonical} ${root} ${all} = some ${list(v.expected.map(i => ranks[i]))}`,
            `  rw [chain_replay_converges (registryModel ${g}) ${model} ${canonical} ${root} ${all} acyclic${n} (by decide) (by decide)]`, '  decide');
        for (const order of v.orders) {
            const delivered = list(order.map(t => receiptRanks[t]));
            const operations = list(order.map(t => owners[t]));
            lines.push(`example : registryReplay ${g} ${r} ${delivered} ${operations} = some ${list(v.expected.map(i => ranks[i]))} := by`,
                `  have h := registry_replay_same_evidence ${g} ${r} ${canonical} ${delivered} ${all} ${operations}`,
                `    (bounded_membership_agrees ${count} _ _ (by decide) (by decide) (by decide))`,
                `    (bounded_membership_agrees ${size} _ _ (by decide) (by decide) (by decide))`,
                `    ordered${n} depthBound${n} (by decide) (by decide)`, `  exact h.symm.trans settled${n}`);
            replays++;
            for (let a = 0; a < size; a++) for (let b = a + 1; b < size; b++) {
                if (parents[a] === null || parents[a] !== parents[b]) continue;
                lines.push(`example : chainPriority ${model} ${delivered} ${a} < chainPriority ${model} ${delivered} ${b} ↔`,
                    `    compare (positions${n} ${preferred[a]}) (positions${n} ${preferred[b]}) = .lt := by`,
                    `  have h := registry_sibling_priority ${g} ${r} positions${n} ordinalRanks${n} (by decide) ${delivered} ${a} ${b} ${parents[a]} (by decide) (by decide) (by decide) (by decide)`,
                    `  have wa : winner (registryAnchors ${g} ${r}) ${a} ${delivered} = ${preferred[a]} := by decide`,
                    `  have wb : winner (registryAnchors ${g} ${r}) ${b} ${delivered} = ${preferred[b]} := by decide`,
                    `  simpa only [${model}, wa, wb] using h`);
                comparisons++;
            }
            for (let op = 0; op < size; op++) {
                lines.push(`example : anchorScan ${model} ${op} ${delivered} ${count} = ${preferred[op]} := by`,
                    `  have h := registry_anchors_same_evidence ${g} ${r} ${op} ${delivered} ${canonical}`,
                    `    (bounded_membership_agrees ${count} _ _ (by decide) (by decide) (by decide))`,
                    '  exact h.trans (by decide)');
                anchors++;
                for (const t of ranked.filter(t => matches(op, t))) {
                    lines.push(`example : anchorScan ${model} ${op} ${delivered} ${receiptRanks[t]} = ${preferred[op]} := by`,
                        `  have h := registry_anchor_warm_agrees ${g} ${r} ${op} ${delivered} ${receiptRanks[t]} (by decide) (by decide)`,
                        '  exact h.trans (by decide)');
                    warm++;
                }
            }
        }
        for (const order of v.orders) {
            const evidence = list(order.map(t => owners[t]));
            for (let next = 0; next < size; next++) {
                if (next === root) continue;
                const path = ancestors(parents[next]);
                const expected = names.indexOf(projection.expectedRegistries[v.ids.indexOf(ids[next])]);
                lines.push(`example : expectedRegistry ${g} ${next} = some ${expected} := by`,
                    `  have h := expected_registry_after_prefix ${g} ordered${n} (by decide) (by decide) ${evidence} ${list(path)} ${valid(path)} ${next} (by decide) (by decide)`,
                    '  exact h.trans (by decide)');
                prefixes++;
            }
            const path = projection.path.slice(1).map(i => ranks[i]);
            lines.push(`example : registryAt ${g} ${ranks[projection.path.at(-1)]} = some ${names.indexOf(projection.registry)} := by`,
                `  have h := registry_prefix_agrees ${g} ordered${n} (by decide) ${evidence} ${root} ${list(path)} ${valid(path)} ${initial} (registry_at_root _ (by decide))`,
                '  exact h.trans (by decide)');
            orders++;
        }
    });
    lines.push('end Archon.RegistryFixtures', '');
    return { result: lines.join('\n'), orders, prefixes, receipts, anchors, warm, replays, comparisons };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const input = JSON.parse(readFileSync(new URL('../../tests/convergence/migration-vectors.json', import.meta.url), 'utf8'));
    const { result } = generateRegistryFixtures(input);
    const destination = new URL('./RegistryFixtures.lean', import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), result, 'registry fixtures are stale');
    else writeFileSync(destination, result);
}
