import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { componentGraph } from '../../tests/convergence/component-model.mjs';
const list = values => '[' + values.join(', ') + ']';
const state = value => value === null ? 'none' : value === 'deleted' ? 'some AgentState.deleted' : 'some (AgentState.active ' + value + ')';

export function generateComponentFixtures(vectors) {
    const lines = ['-- Generated by generate-component-fixtures.mjs; do not edit.', 'import AgentComponents',
        'set_option warningAsError true', 'set_option maxRecDepth 10000', 'set_option maxHeartbeats 4000000', 'namespace Archon.ComponentFixtures'];
    for (const [v, vector] of vectors.entries()) {
        const graph = componentGraph(vector);
        const { ranks, root } = graph;
        // Intern opaque JSON values once; do not repeat large string equality
        // reductions in every delivery trace. The general theorem is polymorphic.
        const atoms = [...new Set([{}, { id: vector.did }, graph.registration,
            ...graph.fullDocuments, ...vector.operations.flatMap(op => Object.values(op.doc ?? {}))].map(value => JSON.stringify(value)))].sort();
        const token = value => {
            const index = atoms.indexOf(JSON.stringify(value));
            if (index < 0) throw new Error('Expected component is not an input value');
            return index;
        };
        lines.push(`def atom${v} : Nat → String := fun i => ${list(atoms.map(value => JSON.stringify(value)))}.getD i ""`);
        atoms.forEach((value, i) => lines.push(`example : atom${v} ${i} = ${JSON.stringify(value)} := by rfl`));
        const indices = ranks.map((_, rank) => ranks.indexOf(rank));
        const lookup = (values, fallback) => '(fun i => ' + list(indices.map(i => values[i])) + '.getD i (' + fallback + '))';
        const documents = list(graph.documents.map(methods => list(methods.map(m => `⟨${m.id}, ${m.key}⟩`))));
        lines.push(`def graph${v} : DocumentGraph := {`, `  size := ${ranks.length}`, `  root := ${root}`, `  initialDocument := ${root}`,
            `  parent := ${lookup(graph.parents.map(p => p === null ? 'none' : 'some ' + ranks[p]), 'none')}`,
            `  depth := ${lookup(graph.depths, '0')}`,
            `  action := ${lookup(graph.actions.map(a => a === 'keep' ? 'AgentAction.keep' : a === 'delete' ? 'AgentAction.deactivate' : 'AgentAction.rotate ' + a), 'AgentAction.keep')}`,
            `  documents := fun i => (${documents} : List (List VerificationMethod)).getD i []`,
            `  named := ${lookup(graph.named, '0')}`,
            `  signatureValid := fun i k => (${lookup(vector.signatureValid.map(list), '[]')}) i |>.getD k false`, '}');
        for (const i of indices) lines.push(`example : agentStateAt (documentAgent graph${v}) ${ranks[i]} = ${state(vector.states[i])} := by decide`);
        const patch = vector.operations.map(op => {
            const member = key => Object.hasOwn(op.doc ?? {}, key) ? 'some ' + token(op.doc[key]) : 'none';
            return '⟨' + member('didDocumentData') + ', ' + member('didDocumentRegistration') + '⟩';
        });
        lines.push(`def patch${v} : Nat → ComponentPatch Nat Nat := ${lookup(patch, '⟨none, none⟩')}`,
            `def documents${v} : Nat → Nat := fun i => ${list(graph.fullDocuments.map(token))}.getD i 0`);
        for (const scenario of vector.scenarios) {
            for (const order of scenario.orders) {
                const records = list(order.map(i => `⟨${ranks[i]}, true, 0⟩`));
                const expected = list(scenario.expected.map(i => ranks[i]));
                const components = scenario.components;
                const initial = '⟨.active graph' + v + '.initialDocument, ' + token({}) + ', ' + token(graph.registration) + '⟩';
                const result = '(' + token(components.didDocument) + ', ' + token(components.didDocumentData) + ', ' + token(components.didDocumentRegistration) + ')';
                lines.push(`example : (replayFullCold (agentModel (documentAgent graph${v})) graph${v}.root (${records} : List (EventRecord Nat))).map (fun s => (recordIds (historyRecords s), (runComponents graph${v} patch${v} ${token({})} ${initial} (recordIds s.2)).map (componentResult documents${v} ${token({ id: vector.did })}))) = some (${expected}, some ${result}) := by decide`);
            }
        }
    }
    lines.push('end Archon.ComponentFixtures', '');
    return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const source = new URL('../../tests/convergence/component-vectors.json', import.meta.url);
    const destination = new URL('./ComponentFixtures.lean', import.meta.url);
    const output = generateComponentFixtures(JSON.parse(readFileSync(source, 'utf8')));
    if (process.argv.includes('--check')) {
        if (readFileSync(destination, 'utf8') !== output) throw new Error('Component fixtures are stale');
    } else writeFileSync(destination, output);
}
