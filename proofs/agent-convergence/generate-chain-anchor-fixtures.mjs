import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

// Exact lexicographic order for the complete ordinal, including prefix length.
export function comparePositions(a, b) {
    for (let i = 0; i < Math.min(a.length, b.length); i++) {
        if (a[i] !== b[i]) return a[i] < b[i] ? -1 : 1;
    }
    return Math.sign(a.length - b.length);
}

// This bridge projects controller anchors only. Their authorization is assumed
// fixed after predecessor reconstruction; signatures are checked by both runtimes.
export function generateChainAnchorFixtures(vectors) {
    const lines = ['-- Generated by generate-chain-anchor-fixtures.mjs; do not edit.',
        'import ChainAnchors', '', 'set_option warningAsError true', '',
        'namespace Archon.ChainAnchorFixtures', ''];
    let count = 0;
    vectors.forEach((vector, v) => {
        const operations = [];
        const tokens = new Map();
        for (const [i, event] of vector.events.entries()) {
            const op = event.operation;
            if (!(op.did === vector.did || (op.type === 'create' && op.registration?.type === 'agent'))) continue;
            const serialized = JSON.stringify(op);
            let index = operations.findIndex(item => JSON.stringify(item) === serialized);
            if (index < 0) { index = operations.length; operations.push(op); }
            tokens.set(i, index);
        }
        const root = operations.find(op => op.type === 'create');
        assert(root && operations.filter(op => op.type === 'create').length === 1, 'one agent genesis required');
        assert.equal(operations[0], root, 'genesis must lead the operation table');
        assert.equal(root.controller, undefined, 'self-controlled agent required');
        assert(!['local', 'hyperswarm', 'pin'].includes(root.registration.registry), 'expected chain required');
        operations.forEach((op, i) => {
            if (!i) return;
            assert.equal(op.type, 'update', 'only settled agent updates supported');
            assert.equal(op.previd, vector.ids[i - 1], 'predecessor-linked operation table required');
            assert.equal(op.doc?.didDocumentRegistration, undefined, 'registry migrations are outside this model');
            assert.equal(op.doc?.didDocument?.controller, undefined, 'external controller is outside this model');
        });
        const anchors = [...tokens].filter(([i]) => vector.events[i].registry !== 'hyperswarm');
        anchors.forEach(([i]) => {
            const e = vector.events[i];
            assert.equal(e.registry, root.registration.registry, 'foreign registry is outside this model');
            assert(Array.isArray(e.ordinal) && e.ordinal.length && e.ordinal.every(n => Number.isSafeInteger(n) && n >= 0), 'complete integer ordinal required');
        });
        anchors.sort(([a], [b]) => comparePositions(vector.events[a].ordinal, vector.events[b].ordinal));
        for (let i = 1; i < anchors.length; i++) {
            assert(comparePositions(vector.events[anchors[i - 1][0]].ordinal, vector.events[anchors[i][0]].ordinal) < 0, 'tied positions are outside this model');
        }
        assert(operations.every((_, op) => anchors.some(([, owner]) => owner === op)), 'each operation needs an anchor');
        const size = anchors.length;
        const list = xs => `[${xs.join(', ')}]`;
        const ranks = new Map(anchors.map(([token], rank) => [token, rank]));
        lines.push(`-- Rank -> source event token: ${JSON.stringify(anchors.map(([token]) => token))}`,
            `def model${v} : AnchorModel where`, `  size := ${size}`,
            '  parent := fun rank => match rank with',
            ...anchors.map(([, op], rank) => `    | ${rank} => some ${op}`),
            '    | _ => none', '  authorized := fun _ => true', '  level := fun _ => 0', '');
        vector.orders.forEach((order, k) => {
            assert(order.every(i => Number.isInteger(i) && vector.events[i]), 'unknown event token');
            const projected = order.filter(i => ranks.has(i)).map(i => ranks.get(i));
            assert.equal(new Set(projected).size, size, 'complete anchor evidence required');
            operations.forEach((_, op) => {
                const eligible = anchors.flatMap(([, owner], rank) => owner === op ? [rank] : []);
                const expected = eligible[0];
                lines.push(`example : anchorScan model${v} ${op} ${list(projected)} ${size} = ${expected} := by`,
                    `  change anchorScan model${v} ${op} ${list(projected)} model${v}.size = ${expected}`,
                    `  rw [anchor_scan_cold]`, '  decide');
                for (const warm of eligible) {
                    lines.push(`example : anchorScan model${v} ${op} ${list(projected)} ${warm} = ${expected} := by`,
                        `  rw [anchor_scan_from_retained model${v} ${op} ${list(projected)} ${warm} (by decide) (by decide)]`, '  decide');
                }
                count++;
            });
        });
    });
    lines.push('', 'end Archon.ChainAnchorFixtures', '');
    return { result: lines.join('\n'), count };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const vectors = JSON.parse(readFileSync(new URL('../../tests/convergence/chain-anchor-vectors.json', import.meta.url), 'utf8'));
    const { result } = generateChainAnchorFixtures(vectors);
    const destination = new URL('./ChainAnchorFixtures.lean', import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), result, 'chain anchor fixtures are stale');
    else writeFileSync(destination, result);
}
