import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { assetGraph, assetRegistryNames, assetScenario } from '../../tests/convergence/asset-model.mjs';
import { generateAssetFixtures } from './generate-asset-fixtures.mjs';
const list = xs => `[${xs.join(', ')}]`;
const splitFin = size => [`  have cases : ${Array.from({ length: size }, (_, i) => 'i.val = ' + i).join(' ∨ ')} := by omega`,
    `  rcases cases with ${Array(size).fill('h').join(' | ')}`];

export function generateProtocolFixtures(vectors) {
    // Reuse the signed-table validation, including expected payloads and all
    // delivery permutations. The final bridge must not bypass the A/B decoder.
    generateAssetFixtures(vectors);
    const names = assetRegistryNames(vectors);
    const lines = ['-- Generated by generate-protocol-fixtures.mjs; do not edit.', 'import ProtocolConvergence', 'import AssetFixtures',
        'set_option warningAsError true', 'set_option maxRecDepth 10000', 'set_option synthInstance.maxSize 2048', 'set_option maxHeartbeats 8000000',
        'namespace Archon.ProtocolFixtures'];
    vectors.forEach((v, n) => {
        const d = assetGraph(v, names), size = d.ownerNames.length;
        const ap = 'AssetFixtures.', cp = 'AssetControllerFixtures.';
        const assetIndex = d.ownerNames.indexOf(v.did);
        assert(assetIndex >= 0);
        const agents = v.controllers.map((c, j) => ({ owner: d.ownerNames.indexOf(c.did), cn: n * 2 + j }));
        for (const [j, { cn }] of agents.entries()) {
            const cv = d.controllerVectors[j], cg = d.controllers[j];
            const atoms = [...new Set([{}, { id: cv.did }, cg.registration, ...cg.fullDocuments,
                ...cv.operations.flatMap(op => Object.values(op.doc ?? {}))].map(JSON.stringify))].sort();
            const deleted = atoms.indexOf(JSON.stringify({ id: cv.did }));
            lines.push(`def agent${n}_${j} : ProtocolAgent := ⟨${ap}spec${n}_${j}, ${cp}receipts${cn}, ${cp}positions${cn}, ${Date.parse(cv.operations[cg.ranks.indexOf(cg.root)].created)}, ${cp}operationTime${cn}, ${cp}chainFacts${cn}, ${cp}documents${cn}, ${cp}methods${cn}, ${deleted}⟩`,
                `theorem agentDomain${n}_${j} : ProtocolAgentDomain agent${n}_${j} := by`,
                `  refine ⟨${cp}ordered${cn}, ${cp}bounded${cn}, ${cp}parents${cn}, by decide, by decide, by decide, by decide, ${cp}methods_agree${cn}, ${cp}ranks${cn}, ?_, ?_⟩`,
                '  · intro rank bound; rfl',
                '  · intro rank bound', `    have small : rank < ${cg.anchors.length} := bound`,
                `    have checked : ∀ rank : Fin ${cg.anchors.length}, (${cp}chainFacts${cn} rank.val).registry = (${cp}receipts${cn}).registry rank.val ∧ (${cp}chainFacts${cn} rank.val).ordinal = ${cp}positions${cn} rank.val ∧ ${cp}positions${cn} rank.val ≠ [] := by decide`,
                '    exact checked ⟨rank, small⟩');
        }
        lines.push(`def asset${n} : ProtocolAsset := ⟨${ap}graph${n}, ${ap}receipts${n}, ${ap}positions${n}, ${Date.parse(v.operations[d.root].created)}, ${ap}chainFacts${n}⟩`,
            `theorem assetDomain${n} : ProtocolAssetDomain asset${n} := by`,
            `  refine ⟨${ap}ordered${n}, ${ap}bounded${n}, ${ap}parents${n}, by decide, by decide, ${ap}ranks${n}, ?_⟩`,
            '  intro rank bound', `  have small : rank < ${d.anchors.length} := bound`,
            `  have checked : ∀ rank : Fin ${d.anchors.length}, (${ap}chainFacts${n} rank.val).registry = (${ap}receipts${n}).registry rank.val ∧ (${ap}chainFacts${n} rank.val).ordinal = ${ap}positions${n} rank.val ∧ ${ap}positions${n} rank.val ≠ [] := by decide`,
            '  exact checked ⟨rank, small⟩');
        const slots = d.ownerNames.map((_, i) => {
            const agent = agents.findIndex(a => a.owner === i);
            return agent >= 0 ? `some (.agent agent${n}_${agent})` : i === assetIndex ? `some (.asset asset${n})` : 'none';
        });
        lines.push(`def world${n} : ProtocolModel ${size} := ⟨fun i => ${list(slots)}.getD i.val none, ${ap}unanchored, ${names.indexOf('local')}⟩`,
            `theorem domain${n} : ProtocolDomain world${n} := by`, `  apply protocol_domain_of_slots`,
            '  · intro i spec entry', ...splitFin(size).map(line => '  ' + line),
            `    all_goals simp only [world${n}, h, List.getD_cons_zero, List.getD_cons_succ] at entry`);
        // Reduce each concrete slot without expanding agent/asset records.
        lines.push('    all_goals simp only [Option.some.injEq, ProtocolDID.agent.injEq, reduceCtorEq] at entry',
            '    all_goals first | contradiction | subst spec',
            `    all_goals first | exact agentDomain${n}_0 | exact agentDomain${n}_1`,
            '  · intro i spec entry', ...splitFin(size).map(line => '  ' + line),
            `    all_goals simp only [world${n}, h, List.getD_cons_zero, List.getD_cons_succ] at entry`,
            '    all_goals simp only [Option.some.injEq, ProtocolDID.asset.injEq, reduceCtorEq] at entry',
            '    all_goals first | contradiction | subst spec', `    all_goals exact assetDomain${n}`,
            '  · intro i spec entry rank bound', ...splitFin(size).map(line => '  ' + line),
            `    all_goals simp only [world${n}, h, List.getD_cons_zero, List.getD_cons_succ] at entry`,
            '    all_goals simp only [Option.some.injEq, ProtocolDID.agent.injEq, reduceCtorEq] at entry',
            '    all_goals first | contradiction | subst spec');
        agents.map((a, j) => ({ ...a, j })).sort((a, b) => a.owner - b.owner).forEach(({ cn, j }) => {
            lines.push(`    · have small : rank < ${d.controllers[j].anchors.length} := bound`,
                `      have checked : ∀ rank : Fin ${d.controllers[j].anchors.length}, (${cp}receipts${cn}).chain ((${cp}receipts${cn}).registry rank.val) = !${ap}unanchored ((${cp}receipts${cn}).registry rank.val) := by decide`,
                '      exact checked ⟨rank, small⟩');
        });
        lines.push('  · intro i spec entry rank bound', ...splitFin(size).map(line => '  ' + line),
            `    all_goals simp only [world${n}, h, List.getD_cons_zero, List.getD_cons_succ] at entry`,
            '    all_goals simp only [Option.some.injEq, ProtocolDID.asset.injEq, reduceCtorEq] at entry',
            '    all_goals first | contradiction | subst spec',
            `    all_goals have small : rank < ${d.anchors.length} := bound`,
            `    all_goals have checked : ∀ rank : Fin ${d.anchors.length}, (${ap}receipts${n}).chain ((${ap}receipts${n}).registry rank.val) = !${ap}unanchored ((${ap}receipts${n}).registry rank.val) := by decide`,
            '    all_goals exact checked ⟨rank, small⟩',
            `def empty${n} : ProtocolRecords ${size} Nat := ⟨fun _ => [], fun _ => []⟩`);
        v.stages.forEach((stage, s) => {
            const suffix = `${n}_${s}`;
            stage.orders.forEach((_, k) => {
                lines.push(`def evidence${suffix}_${k} : ProtocolEvidence ${size} Nat := fun i => if i.val = ${assetIndex} then ${ap}sources${suffix}_${k} else ${ap}agents${suffix}_${k} i.val`);
            });
            lines.push(`theorem sources${suffix} : ProtocolSources world${n} evidence${suffix}_0 := by`,
                `  have checked : ∀ i : Fin ${size}, ∀ source ∈ evidence${suffix}_0 i, protocolSourceValid world${n} i source.key = true := by decide`,
                '  exact checked',
            );
            stage.orders.forEach((_, k) => {
                lines.push(`def raw${suffix}_${k} : ProtocolReceiptEvidence ${size} Nat := fun i =>`,
                    `  withIncompleteProtocolReceipts ${k === 1} (protocolReceiptsOfSources world${n} evidence${suffix}_${k} i)`,
                    `theorem normalized${suffix}_${k} : normalizeProtocolEvidence raw${suffix}_${k} = evidence${suffix}_${k} := by`,
                    `  have checked : ∀ i : Fin ${size}, normalizeProtocolEvidence raw${suffix}_${k} i = evidence${suffix}_${k} i := by decide`,
                    '  exact funext checked');
            });
            lines.push(`theorem rawSources${suffix} : ProtocolReceiptSources world${n} raw${suffix}_0 := by`,
                `  have checked : ∀ i : Fin ${size}, ∀ receipt ∈ raw${suffix}_0 i, ProtocolReceiptValid world${n} i (raw${suffix}_0 i) receipt := by decide`,
                '  exact checked',
                `example := protocol_convergence world${n} domain${n} raw${suffix}_0 rawSources${suffix}`);
            stage.orders.forEach((_, k) => {
                lines.push(`theorem same${suffix}_${k} : SameProtocolEvidence evidence${suffix}_0 evidence${suffix}_${k} := by`,
                    `  have checked : ∀ i : Fin ${size}, sameAgentSourceCheck (evidence${suffix}_0 i) (evidence${suffix}_${k} i) = true := by decide`,
                    '  exact fun i => same_sources_of_check _ _ (checked i)',
                    `example := protocol_sources_shared world${n} evidence${suffix}_0 evidence${suffix}_${k} sources${suffix} same${suffix}_${k}`,
                    `theorem rawSame${suffix}_${k} : SameProtocolReceiptEvidence raw${suffix}_0 raw${suffix}_${k} := by`,
                    `  have checked : ∀ i : Fin ${size}, sameProtocolReceiptCheck (raw${suffix}_0 i) (raw${suffix}_${k} i) = true := by decide`,
                    '  exact fun i => same_protocol_receipts_of_check _ _ (checked i)',
                    `example := protocol_receipt_sources_shared world${n} raw${suffix}_0 raw${suffix}_${k} rawSources${suffix} rawSame${suffix}_${k}`);
            });
            // Compare every DID's complete semantic projection in every order,
            // including decoded agent documents/deactivation and receipt views.
            stage.orders.forEach((_, k) => {
                const run = `(reconcileProtocol world${n} (normalizeProtocolEvidence raw${suffix}_${k}) empty${n})`;
                const anchor = `(assetAnchors ${ap}graph${n} ${ap}receipts${n})`;
                const model = `(coldAssetModel ${ap}graph${n} ${anchor})`;
                const expectedResults = d.ownerNames.map((_, owner) => {
                    const j = agents.findIndex(agent => agent.owner === owner);
                    return j >= 0
                        ? `(controllerSourceStop ${ap}inputs${n} ${owner} ${ap}spec${n}_${j} (${ap}agents${suffix}_${k} ${owner})).map (fun records => some (Sum.inl (protocolAgentResult ${names.indexOf('local')} agent${n}_${j} records)))`
                        : owner === assetIndex
                            ? `(stopWhenStable (rankedPass ${model} (chainOwner ${anchor}) ${ap}graph${n}.size ${ap}records${suffix}_${k}) (${model}.size + 3) []).map (fun records => some (Sum.inr (assetReceiptResult ${ap}graph${n} ${ap}receipts${n} (asset${n}.operationTime ${names.indexOf('local')}) ${ap}chainFacts${n} records)))`
                            : 'some none';
                });
                lines.push(`example : ${run}.map (fun result => List.ofFn (protocolResult world${n} result)) = (do`,
                    ...expectedResults.map((value, owner) => '  let result' + owner + ' ← ' + value),
                    `  pure ${list(expectedResults.map((_, owner) => 'result' + owner))}) := by`,
                    `  rw [normalized${suffix}_${k}]`, '  decide');
            });
            assert.deepEqual(assetScenario(v, d, stage.evidence).expected, stage.expected);
        });
    });
    // A direct local receipt may create a chain-registered agent. Its mismatched
    // root receipt has no cutoff clock in the authorization view. Use the same
    // distinct-time signed case that both production ports exercise.
    const clocks = JSON.parse(readFileSync(new URL('../../tests/convergence/local-receipt-counterexample.json', import.meta.url), 'utf8'));
    clocks.forEach((v, i) => {
        const op = v.nonlocalGenesis;
        assert.equal(op.type, 'create');
        assert.equal(op.registration.registry, 'BTC:signet');
        assert.notEqual(op.created, op.proof.created);
        const created = Date.parse(op.created), proof = Date.parse(op.proof.created);
        assert(Number.isFinite(created) && Number.isFinite(proof));
        lines.push(`def localClockSource${i} : AgentSourceReceipt Nat := ⟨⟨0, 0, none⟩, 0⟩`,
            `example (a : AnchorModel) (facts : Nat → ChainReceiptView) :`,
            `    agentReceiptView a (fun _ => some 1)`,
            `      (protocolOperationTime 0 1 0 ${created} (fun _ => ${proof})) facts`,
            `      ⟨a.size, false, localClockSource${i}⟩ = ⟨0, false, .unconfirmed⟩ := by`,
            `  simpa [localClockSource${i}] using protocol_provisional_receipt_view a (fun _ => some 1)`,
            `    0 1 0 ${created} (fun _ => ${proof}) facts localClockSource${i} rfl`);
    });
    lines.push('end Archon.ProtocolFixtures', '');
    return lines.join('\n');
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const vectors = JSON.parse(readFileSync(new URL('../../tests/convergence/asset-vectors.json', import.meta.url), 'utf8'));
    const code = generateProtocolFixtures(vectors), target = new URL('ProtocolFixtures.lean', import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8'), code);
    else writeFileSync(target, code);
}
