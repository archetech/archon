import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { isDeepStrictEqual } from 'node:util';

// This checks the modeled shape, not cryptographic validity. The signed-source
// generator and ordinary runtime suites check the signature oracle separately.
function deriveGraph(vector) {
    const { operations, ids, keys, did } = vector;
    const creates = operations.flatMap((op, i) => op.type === 'create' ? [i] : []);
    if (creates.length !== 1) throw new Error('Expected exactly one create operation');
    if (ids.length !== operations.length || new Set(ids).size !== ids.length) throw new Error('Expected distinct canonical CIDs');
    const root = creates[0];
    const create = operations[root];
    const genesisKey = keys.findIndex(key => isDeepStrictEqual(key, create.publicJwk));
    if (genesisKey < 0 || create.previd !== undefined || did !== 'did:cid:' + ids[root]
        || !isDeepStrictEqual(create.registration, { version: 1, type: 'agent', registry: 'hyperswarm' })
        || Object.keys(create).some(key => !['type', 'created', 'registration', 'publicJwk', 'proof'].includes(key))) {
        throw new Error('Expected a self-controlled single-key hyperswarm genesis');
    }
    const parents = operations.map((op, i) => {
        if (i === root) return null;
        const parent = ids.indexOf(op.previd);
        if (parent < 0) throw new Error('Fixture predecessor is not a canonical operation ID');
        return parent;
    });
    const actions = operations.map((op, i) => {
        if (i === root) return 'keep';
        if (op.did !== did || !['update', 'delete'].includes(op.type)
            || Object.keys(op).some(key => !['type', 'did', 'previd', 'doc', 'proof'].includes(key))) {
            throw new Error('Operation is outside the single-key agent model');
        }
        if (op.type === 'delete') {
            if (Object.hasOwn(op, 'doc')) throw new Error('Deletion must not contain an update document');
            return 'delete';
        }
        if (!op.doc || Object.keys(op.doc).length !== 1) throw new Error('Expected data-only update or single-key replacement');
        if (Object.hasOwn(op.doc, 'didDocumentData')) return 'keep';
        const document = op.doc.didDocument;
        const methods = document?.verificationMethod;
        if (!Array.isArray(methods) || methods.length !== 1) throw new Error('Expected one verification method');
        const method = methods[0];
        const key = keys.findIndex(candidate => isDeepStrictEqual(candidate, method.publicKeyJwk));
        const id = '#key-' + (key + 1);
        const expected = {
            '@context': ['https://www.w3.org/ns/did/v1'], id: did,
            verificationMethod: [{ id, controller: did, type: 'EcdsaSecp256k1VerificationKey2019', publicKeyJwk: keys[key] }],
            authentication: [id], assertionMethod: [id], capabilityInvocation: [id],
        };
        if (key < 0 || !isDeepStrictEqual(document, expected)) throw new Error('Replacement is outside the single-key agent model');
        return key;
    });
    if (!isDeepStrictEqual(parents, vector.parents) || !isDeepStrictEqual(actions, vector.actions)) {
        throw new Error('Precomputed graph disagrees with operation records');
    }
    return { root, genesisKey, parents, actions };
}

export function generateAgentFixtures(vectors) {
    const lines = ['-- Generated by generate-agent-fixtures.mjs; do not edit.', 'import AgentAuthorization', 'set_option warningAsError true', 'set_option maxRecDepth 10000', 'set_option maxHeartbeats 4000000', 'namespace Archon.AgentFixtures'];
    const list = values => `[${values.join(', ')}]`;
    const state = value => value === null ? 'none' : value === 'deleted' ? 'some AgentState.deleted' : `some (AgentState.active ${value})`;
    for (const [v, vector] of vectors.entries()) {
        const { root, genesisKey, parents, actions: derivedActions } = deriveGraph(vector);
        const ranks = vector.ids.map(id => [...vector.ids].sort().indexOf(id));
        const depth = (i, seen = new Set()) => {
            if (seen.has(i)) throw new Error('Cyclic fixture');
            return parents[i] === null ? 0 : 1 + depth(parents[i], new Set([...seen, i]));
        };
        const lookup = (values, fallback = '0') => `(fun i => ${list(ranks.map((_, rank) => values[ranks.indexOf(rank)]))}.getD i (${fallback}))`;
        const actions = derivedActions.map(a => a === 'keep' ? 'AgentAction.keep' : a === 'delete' ? 'AgentAction.deactivate' : `AgentAction.rotate ${a}`);
        lines.push(`def graph${v} : AgentGraph := {`, `  size := ${ranks.length}`, `  root := ${ranks[root]}`, `  genesisKey := ${genesisKey}`,
            `  parent := ${lookup(parents.map(p => p === null ? 'none' : 'some ' + ranks[p]), 'none')}`,
            `  action := ${lookup(actions, 'AgentAction.keep')}`,
            `  validBy := fun i k => (${lookup(vector.validBy.map(row => list(row)), '[]')}) i |>.getD k false`,
            `  depth := ${lookup(ranks.map((_, i) => depth(i)))}`, '}');
        // Finite lookup functions default outside the table. Their concrete states
        // and replay results are kernel checked, without native_decide or axioms.
        ranks.map((_, rank) => ranks.indexOf(rank)).forEach(i => lines.push(`example : agentStateAt graph${v} ${ranks[i]} = ${state(vector.states[i])} := by decide`));
        for (const scenario of vector.scenarios) {
            for (const order of scenario.orders) {
                const records = list(order.map(i => `⟨${ranks[i]}, true, 0⟩`));
                lines.push(`example : (replayFullCold (agentModel graph${v}) graph${v}.root (${records} : List (EventRecord Nat))).map (fun s => (recordIds (historyRecords s), runAgent graph${v} (.active ${genesisKey}) (recordIds s.2))) = some (${list(scenario.expected.map(i => ranks[i]))}, ${state(scenario.finalState)}) := by decide`);
            }
        }
    }
    lines.push('end Archon.AgentFixtures', '');
    return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const source = new URL('../../tests/convergence/agent-vectors.json', import.meta.url);
    const destination = new URL('./AgentFixtures.lean', import.meta.url);
    const output = generateAgentFixtures(JSON.parse(readFileSync(source, 'utf8')));
    if (process.argv.includes('--check')) {
        if (readFileSync(destination, 'utf8') !== output) throw new Error('Agent fixtures are stale');
    } else writeFileSync(destination, output);
}
