import { readFileSync, writeFileSync } from 'node:fs';
const vectors = JSON.parse(readFileSync('tests/convergence/agent-vectors.json', 'utf8'));
const lines = ['-- Generated by generate-agent-fixtures.mjs; do not edit.', 'import AgentAuthorization', 'set_option maxRecDepth 10000', 'set_option maxHeartbeats 4000000', 'namespace Archon.AgentFixtures'];
const list = values => `[${values.join(', ')}]`;
const state = value => value === null ? 'none' : value === 'deleted' ? 'some AgentState.deleted' : `some (AgentState.active ${value})`;
for (const [v, vector] of vectors.entries()) {
    const ranks = vector.ids.map(id => [...vector.ids].sort().indexOf(id));
    const depth = i => vector.parents[i] === null ? 0 : 1 + depth(vector.parents[i]);
    const lookup = (values, fallback = '0') => `(fun i => ${list(ranks.map((_, rank) => values[ranks.indexOf(rank)]))}.getD i (${fallback}))`;
    const actions = vector.actions.map(a => a === 'keep' ? 'AgentAction.keep' : a === 'delete' ? 'AgentAction.deactivate' : `AgentAction.rotate ${a}`);
    lines.push(`def graph${v} : AgentGraph := {`, `  size := ${ranks.length}`, `  root := ${ranks[0]}`, '  genesisKey := 0',
        `  parent := ${lookup(vector.parents.map(p => p === null ? 'none' : 'some ' + ranks[p]), 'none')}`,
        `  action := ${lookup(actions, 'AgentAction.keep')}`,
        `  validBy := fun i k => (${lookup(vector.validBy.map(row => list(row)), '[]')}) i |>.getD k false`,
        `  depth := ${lookup(ranks.map((_, i) => depth(i)))}`, '}');
    // Finite lookup functions default outside the table. Their concrete states
    // and replay results are kernel checked, without native_decide or axioms.
    vector.states.forEach((s, i) => lines.push(`example : agentStateAt graph${v} ${ranks[i]} = ${state(s)} := by decide`));
    for (const scenario of vector.scenarios) {
        for (const order of scenario.orders) {
            const records = list(order.map(i => `⟨${ranks[i]}, true, 0⟩`));
            lines.push(`example : (replayFullCold (agentModel graph${v}) graph${v}.root (${records} : List (EventRecord Nat))).map (fun s => (recordIds (historyRecords s), runAgent graph${v} (.active 0) (recordIds s.2))) = some (${list(scenario.expected.map(i => ranks[i]))}, ${state(scenario.finalState)}) := by decide`);
        }
    }
}
lines.push('end Archon.AgentFixtures', '');
const output = lines.join('\n');
const path = 'proofs/agent-convergence/AgentFixtures.lean';
if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== output) throw new Error('Agent fixtures are stale');
} else writeFileSync(path, output);
