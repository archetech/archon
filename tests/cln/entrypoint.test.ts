describe('RPC share', () => {
    const gid = String(process.getgid!());
    const shareDir = () => join(root, 'data', 'rpc-share');
    const calls = () => existsSync(join(log, 'socat.calls'))
        ? readFileSync(join(log, 'socat.calls'), 'utf-8').trim().split('\n')
        : [];

    it('relays the RPC socket into a directory of its own for the group', () => {
        expect(run({ RPC_SHARE: 'true', RPC_SHARE_GID: gid }).status).toBe(0);

        expect(calls()).toEqual([
            `UNIX-LISTEN:${shareDir()}/lightning-rpc,fork,unlink-early,mode=0660,group=${gid} ` +
            `UNIX-CONNECT:${lightningDir()}/regtest/lightning-rpc`,
        ]);
        const stat = statSync(shareDir());
        expect(stat.mode & 0o777).toBe(0o750);
        expect(String(stat.gid)).toBe(gid);
    });

    it('runs alongside the Tor relay', () => {
        expect(run(tor({ RPC_SHARE: 'true', RPC_SHARE_GID: gid })).status).toBe(0);
        expect(calls()).toHaveLength(2);
    });

    it('is off by default, and removes a socket left from an earlier start', () => {
        mkdirSync(shareDir(), { recursive: true });
        writeFileSync(join(shareDir(), 'lightning-rpc'), '');

        expect(run().status).toBe(0);
        expect(calls()).toEqual([]);
        expect(existsSync(join(shareDir(), 'lightning-rpc'))).toBe(false);
    });

    it.each([
        ['a missing group', { RPC_SHARE: 'true' }],
        ['a group name instead of an id', { RPC_SHARE: 'true', RPC_SHARE_GID: 'archon' }],
        ['an unknown RPC_SHARE value', { RPC_SHARE: 'yes', RPC_SHARE_GID: '1000' }],
    ])('refuses to start with %s', (_case, extra) => {
        const result = run(extra);

        expect(result.status).not.toBe(0);
        expect(existsSync(join(log, 'lightningd.args'))).toBe(false);
    });

    it('stops lightningd and exits non-zero when the share relay exits', () => {
        const result = run({ RPC_SHARE: 'true', RPC_SHARE_GID: gid, STUB_LIGHTNINGD: 'run', STUB_SOCAT: 'after:0' });

        expect(result.status).toBe(1);
        expect(existsSync(join(log, 'lightningd.stopped'))).toBe(true);
    });
});

describe('supervision', () => {
    it('runs lightningd in the lightning dir with any extra arguments', () => {
        expect(run({}, ['--disable-plugin=bookkeeper']).status).toBe(0);
        expect(readFileSync(join(log, 'lightningd.args'), 'utf-8').trim().split('\n'))
            .toEqual([`--lightning-dir=${lightningDir()}`, '--network=regtest', '--disable-plugin=bookkeeper']);
    });

    it('exits with lightningd\'s status and stops the relay', () => {
        const result = run(tor({ STUB_LIGHTNINGD: 'after:3' }));

        expect(result.status).toBe(3);
    });

    it('stops lightningd and exits non-zero when the relay exits', () => {
        const result = run(tor({ STUB_LIGHTNINGD: 'run', STUB_SOCAT: 'after:0' }));

        expect(result.status).toBe(1);
        expect(existsSync(join(log, 'lightningd.stopped'))).toBe(true);
    });

    it('forwards TERM to lightningd and exits once it has stopped', async () => {
        const child: ChildProcess = spawn('bash', ['docker/cln/entrypoint.sh'], { env: env(tor({ STUB_LIGHTNINGD: 'run' })) });
        const exited = new Promise<number | null>(resolve => child.on('exit', code => resolve(code)));

        // Wait until lightningd is running before signalling.
        const started = join(log, 'lightningd.args');
        for (let i = 0; i < 100 && !existsSync(started); i++) {
            await new Promise(resolve => setTimeout(resolve, 50));
        }
        child.kill('SIGTERM');

        expect(await exited).toBe(0);
        expect(existsSync(join(log, 'lightningd.stopped'))).toBe(true);
    });
});

describe('healthcheck', () => {
    function health(extra: Record<string, string> = {}) {
        stub('lightning-cli', `printf '%s\\n' "$@" > "${log}/lightning-cli.args"; exit "\${STUB_LCLI:-0}"`);
        return spawnSync('bash', ['docker/cln/healthcheck.sh'], { env: env(extra), encoding: 'utf-8', timeout: 20000 });
    }

    it('asks lightningd over its RPC socket', () => {
        expect(health().status).toBe(0);
        expect(readFileSync(join(log, 'lightning-cli.args'), 'utf-8').trim().split('\n'))
            .toEqual([`--rpc-file=${lightningDir()}/regtest/lightning-rpc`, 'getinfo']);
    });

    it('is unhealthy when lightningd does not answer', () => {
        expect(health({ STUB_LCLI: '1' }).status).not.toBe(0);
    });

    it('clearnet: does not probe an onion', () => {
        expect(health().status).toBe(0);
        expect(existsSync(join(log, 'socat.args'))).toBe(false);
    });

    it.each(['tor', 'hybrid'])('%s: probes the onion through Tor', mode => {
        expect(health(tor({ NETWORK_MODE: mode, STUB_SOCAT: 'exit:0' })).status).toBe(0);
        expect(readFileSync(join(log, 'socat.args'), 'utf-8').trim().split('\n'))
            .toEqual(['-T', '20', '/dev/null', `SOCKS4A:tor:${ONION}:9736,socksport=9050`]);
    });

    it.each(['tor', 'hybrid'])('%s: is unhealthy when the onion does not answer', mode => {
        expect(health(tor({ NETWORK_MODE: mode, STUB_SOCAT: 'exit:1' })).status).not.toBe(0);
    });
});
