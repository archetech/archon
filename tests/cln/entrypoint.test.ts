import { ChildProcess, spawn, spawnSync } from 'child_process';
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';

// docker/cln/entrypoint.sh writes the Core Lightning config and supervises
// lightningd. These run the real script with stub lightningd, socat and
// getent on PATH, against a temporary lightning root.

const ONION = 'abcdefghijklmnopqrstuvwxyz234567abcdefghijklmnopqrstuvw.onion';

let root: string;
let bin: string;
let log: string;
let hsDir: string;

function stub(name: string, body: string): void {
    const path = join(bin, name);
    writeFileSync(path, `#!/usr/bin/env bash\n${body}\n`);
    chmodSync(path, 0o755);
}

beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'cln-entrypoint-'));
    bin = join(root, 'bin');
    log = join(root, 'log');
    hsDir = join(root, 'tor');
    mkdirSync(bin);
    mkdirSync(log);
    mkdirSync(hsDir);

    // STUB_<NAME>=exit:N exits at once with N; anything else runs until TERM.
    for (const name of ['lightningd', 'socat']) {
        const control = `STUB_${name.toUpperCase()}`;
        stub(name, `
printf '%s\\n' "$@" > "${log}/${name}.args"
echo "$*" >> "${log}/${name}.calls"
case "\${${control}:-run}" in
    exit:*) exit "\${${control}#exit:}" ;;
    after:*) sleep 0.5; exit "\${${control}#after:}" ;;
esac
trap 'echo stopped > "${log}/${name}.stopped"; exit 0' TERM
while :; do sleep 0.05; done`);
    }
    stub('getent', '[[ "$2" == "$STUB_RESOLVES" ]] && echo "10.0.0.2 $2" || exit 2');
});

afterEach(() => {
    rmSync(root, { recursive: true, force: true });
});

function env(extra: Record<string, string> = {}): NodeJS.ProcessEnv {
    return {
        PATH: `${bin}:${process.env.PATH}`,
        LIGHTNING_ROOT: join(root, 'data'),
        TOR_HS_DIR: hsDir,
        TOR_WAIT_SECONDS: '1',
        NETWORK: 'regtest',
        NETWORK_MODE: 'clearnet',
        BITCOIN_RPCUSER: 'user',
        BITCOIN_RPCPASSWORD: 'secret',
        STUB_LIGHTNINGD: 'exit:0',
        ...extra,
    };
}

function tor(extra: Record<string, string> = {}): Record<string, string> {
    writeFileSync(join(hsDir, 'hostname'), `${ONION}\n`);
    return { NETWORK_MODE: 'tor', STUB_RESOLVES: 'tor', ...extra };
}

function run(extra: Record<string, string> = {}, args: string[] = []) {
    return spawnSync('bash', ['docker/cln/entrypoint.sh', ...args], { env: env(extra), encoding: 'utf-8', timeout: 20000 });
}

