describe('network modes', () => {
    it('tor: proxies everything through the relay and announces the onion', () => {
        expect(run(tor()).status).toBe(0);

        expect(lines()).toEqual(expect.arrayContaining(['proxy=127.0.0.1:9050', 'always-use-proxy=true']));
        expect(announced()).toEqual([`announce-addr=${ONION}:9736`]);
        expect(readFileSync(join(log, 'socat.args'), 'utf-8').trim().split('\n'))
            .toEqual(['TCP-LISTEN:9050,bind=127.0.0.1,fork,reuseaddr', 'TCP:tor:9050']);
    });

    it('tor: also announces ANNOUNCE_ADDR when set', () => {
        expect(run(tor({ ANNOUNCE_ADDR: 'other.onion:9736' })).status).toBe(0);
        expect(announced()).toEqual([`announce-addr=${ONION}:9736`, 'announce-addr=other.onion:9736']);
    });

    it('hybrid: proxies outbound Tor without forcing it, and announces both addresses', () => {
        expect(run(tor({ NETWORK_MODE: 'hybrid', ANNOUNCE_ADDR: 'node.example.com:9736' })).status).toBe(0);

        expect(lines()).toContain('proxy=127.0.0.1:9050');
        expect(config()).not.toContain('always-use-proxy');
        expect(announced()).toEqual([`announce-addr=${ONION}:9736`, 'announce-addr=node.example.com:9736']);
    });

    it.each(['hybrid', 'clearnet'])('%s: writes no announce-addr for an empty ANNOUNCE_ADDR', mode => {
        const extra = mode === 'hybrid' ? tor({ NETWORK_MODE: 'hybrid' }) : {};
        expect(run({ ...extra, ANNOUNCE_ADDR: '' }).status).toBe(0);

        expect(announced()).toEqual(mode === 'hybrid' ? [`announce-addr=${ONION}:9736`] : []);
    });

    it('clearnet: uses no proxy and needs no tor', () => {
        expect(run({ ANNOUNCE_ADDR: 'node.example.com:9736' }).status).toBe(0);

        expect(config()).not.toMatch(/proxy/);
        expect(announced()).toEqual(['announce-addr=node.example.com:9736']);
        expect(existsSync(join(log, 'socat.args'))).toBe(false);
    });

    it('fails, naming the profile, when tor does not resolve', () => {
        const result = run(tor({ STUB_RESOLVES: '' }));

        expect(result.status).not.toBe(0);
        expect(result.stderr).toContain('COMPOSE_PROFILES');
        expect(existsSync(join(log, 'lightningd.args'))).toBe(false);
    });

    it('fails rather than start unannounced when no onion hostname appears', () => {
        const result = run({ NETWORK_MODE: 'tor', STUB_RESOLVES: 'tor' });

        expect(result.status).not.toBe(0);
        expect(result.stderr).toContain('no onion hostname');
        expect(existsSync(join(log, 'lightningd.args'))).toBe(false);
    });

    it('refuses tor mode with the P2P port published beyond loopback', () => {
        const result = run(tor({ P2P_BIND: '0.0.0.0' }));

        expect(result.status).not.toBe(0);
        expect(result.stderr).toContain('ARCHON_CLN_P2P_BIND');
        expect(run(tor({ P2P_BIND: '127.0.0.1' })).status).toBe(0);
        expect(run(tor({ NETWORK_MODE: 'hybrid', P2P_BIND: '0.0.0.0' })).status).toBe(0);
    });
});

