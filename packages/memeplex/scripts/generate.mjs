// Writes src/schemas.ts and src/validators.generated.ts from the published schema
// files in share/schema/memeplex/v1, which hold the reference's normative text.
//
//   node scripts/generate.mjs           write both files
//   node scripts/generate.mjs --check   exit 1 if either file is out of date
//
// The validators are compiled here, not when the package is used: compiling a
// schema at run time builds a function from a string, which a browser extension's
// content security policy forbids.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const SCHEMA_DIR = path.resolve(here, '../../../share/schema/memeplex/v1');
const OUT_DIR = path.resolve(here, '../src');
export const NAMES = ['post', 'paper', 'reply', 'rating', 'tag', 'grant', 'grant-request'];

const HEADER = '// Generated by scripts/generate.mjs from share/schema/memeplex/v1. Do not edit.\n';
const exported = name => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

export function generate() {
    const schemas = Object.fromEntries(NAMES.map(name =>
        [name, JSON.parse(readFileSync(path.join(SCHEMA_DIR, `${name}.json`), 'utf8'))]));

    // The schemas name fields in `required` that the same subschema does not
    // define, and leave some subschemas untyped. Both are ordinary JSON Schema that
    // strict mode objects to; the rest of strict mode, which rejects unknown
    // keywords, stays on.
    const Ajv = Ajv2020.default ?? Ajv2020;
    const standalone = standaloneCode.default ?? standaloneCode;
    const ajv = new Ajv({ strictRequired: false, strictTypes: false, code: { source: true, esm: true } });
    for (const name of NAMES) ajv.addSchema(schemas[name], name);
    const code = standalone(ajv, Object.fromEntries(NAMES.map(name => [exported(name), name])));

    // The compiled code asks for two helpers of the compiler's. The package carries
    // its own, so that it depends on nothing at run time.
    const helpers = { 'ajv/dist/runtime/ucs2length': 'ucs2length', 'ajv/dist/runtime/equal': 'equal' };
    let body = code.replace(/^"use strict";/, '');
    for (const [module, helper] of Object.entries(helpers)) {
        body = body.split(`require("${module}").default`).join(helper);
    }
    if (/require\(/.test(body)) throw new Error('the compiled validators require a module this script does not replace');
    if (/new Function|eval\(/.test(body)) throw new Error('the compiled validators build code at run time');

    return {
        'schemas.ts': `${HEADER}\nexport const schemas = ${JSON.stringify(schemas, null, 4)} as const;\n`,
        'validators.generated.ts': `${HEADER}/* eslint-disable */\n// @ts-nocheck\nimport { equal, ucs2length } from './runtime.js';\n\n${body}\n`,
    };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const files = generate();
    const stale = Object.entries(files).filter(([name, content]) => {
        let current = '';
        try { current = readFileSync(path.join(OUT_DIR, name), 'utf8'); } catch { /* not written yet */ }
        return current !== content;
    }).map(([name]) => name);

    if (process.argv.includes('--check')) {
        if (stale.length) {
            console.error(`out of date: ${stale.join(', ')}. Run: npm run generate -w @didcid/memeplex`);
            process.exit(1);
        }
    } else {
        for (const name of stale) writeFileSync(path.join(OUT_DIR, name), files[name]);
        console.log(stale.length ? `wrote ${stale.join(', ')}` : 'up to date');
    }
}
